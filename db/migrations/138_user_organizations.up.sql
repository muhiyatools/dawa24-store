BEGIN;

CREATE TABLE IF NOT EXISTS org.user_organizations (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    customer_org_id     BIGINT REFERENCES org.organizations(id) ON DELETE SET NULL,
    vendor_org_id       BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    organization_number TEXT NOT NULL,
    status              TEXT NOT NULL DEFAULT 'pending', -- 'pending', 'approved', 'rejected'
    notes               TEXT NOT NULL DEFAULT '',
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at          TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_user_orgs_user ON org.user_organizations (user_id) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_user_orgs_vendor ON org.user_organizations (vendor_org_id) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_user_orgs_cust ON org.user_organizations (customer_org_id) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_user_vendor_org ON org.user_organizations (user_id, vendor_org_id) WHERE deleted_at IS NULL;

CREATE TRIGGER user_organizations_touch BEFORE UPDATE ON org.user_organizations
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

COMMIT;
