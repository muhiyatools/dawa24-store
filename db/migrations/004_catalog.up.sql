-- 004_catalog
--
-- Product catalog: categories, brands, products, product variants (formerly product_childerns),
-- product metadata, and customer mappings.
--
-- Arabic search is supported in-database via trigram GIN indexes over
-- platform.normalize_arabic(name->>'ar').

BEGIN;

-- ---------------------------------------------------------------------------
-- Categories
-- ---------------------------------------------------------------------------
CREATE TABLE catalog.categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id   UUID NOT NULL DEFAULT gen_random_uuid(),
    parent_id   BIGINT REFERENCES catalog.categories(id) ON DELETE SET NULL,
    name        JSONB NOT NULL,
    description JSONB,
    icon        TEXT,
    image       TEXT,
    status      TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
    sort_order  INT NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at  TIMESTAMPTZ
);

CREATE UNIQUE INDEX categories_public_id_key ON catalog.categories (public_id);
CREATE INDEX categories_parent_idx ON catalog.categories (parent_id) WHERE deleted_at IS NULL;
CREATE INDEX categories_status_idx ON catalog.categories (status) WHERE deleted_at IS NULL;
CREATE INDEX categories_name_trgm_idx ON catalog.categories
    USING GIN (platform.normalize_arabic(name->>'ar') gin_trgm_ops);

CREATE TRIGGER categories_touch BEFORE UPDATE ON catalog.categories
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

-- ---------------------------------------------------------------------------
-- Brands
-- ---------------------------------------------------------------------------
CREATE TABLE catalog.brands (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id   UUID NOT NULL DEFAULT gen_random_uuid(),
    name        JSONB NOT NULL,
    description JSONB,
    image       TEXT,
    status      TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at  TIMESTAMPTZ
);

CREATE UNIQUE INDEX brands_public_id_key ON catalog.brands (public_id);
CREATE INDEX brands_status_idx ON catalog.brands (status) WHERE deleted_at IS NULL;
CREATE INDEX brands_name_trgm_idx ON catalog.brands
    USING GIN (platform.normalize_arabic(name->>'ar') gin_trgm_ops);

CREATE TRIGGER brands_touch BEFORE UPDATE ON catalog.brands
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

-- ---------------------------------------------------------------------------
-- Products (Tenant-owned)
-- ---------------------------------------------------------------------------
CREATE TABLE catalog.products (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id               UUID NOT NULL DEFAULT gen_random_uuid(),
    organization_id         BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    category_id             BIGINT REFERENCES catalog.categories(id) ON DELETE SET NULL,
    brand_id                BIGINT REFERENCES catalog.brands(id) ON DELETE SET NULL,
    branch_id               BIGINT REFERENCES org.branches(id) ON DELETE SET NULL,
    name                    JSONB NOT NULL,
    description             JSONB,
    sku                     TEXT,
    barcode                 TEXT,
    price                   NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    discount                NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    old_price               NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    image                   TEXT,
    image_link              TEXT,
    attributes              JSONB NOT NULL DEFAULT '{}'::JSONB,
    status                  TEXT NOT NULL DEFAULT 'active'
                            CHECK (status IN ('active','inactive','pending','rejected')),
    sold_times              BIGINT NOT NULL DEFAULT 0,
    is_featured             BOOLEAN NOT NULL DEFAULT false,

    -- Regulated pharmaceutical attributes (legacy 34-column parity)
    dosage_form             TEXT,
    scientific_name         TEXT,
    pharmacology            TEXT,
    active                  TEXT,
    concentration           TEXT,
    unit                    TEXT,
    units                   TEXT,
    small_unit              TEXT,
    volume                  TEXT,
    manufacturing_companies TEXT,
    company                 TEXT,

    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at              TIMESTAMPTZ
);

CREATE UNIQUE INDEX products_public_id_key ON catalog.products (public_id);
CREATE INDEX products_org_idx      ON catalog.products (organization_id) WHERE deleted_at IS NULL;
CREATE INDEX products_category_idx ON catalog.products (category_id);
CREATE INDEX products_brand_idx    ON catalog.products (brand_id);
CREATE INDEX products_status_idx   ON catalog.products (status) WHERE deleted_at IS NULL;
CREATE INDEX products_barcode_idx  ON catalog.products (barcode) WHERE barcode IS NOT NULL;
CREATE INDEX products_sku_idx      ON catalog.products (sku) WHERE sku IS NOT NULL;

-- Trigram GIN index for fast Arabic fuzzy product search
CREATE INDEX products_name_ar_trgm_idx ON catalog.products
    USING GIN (platform.normalize_arabic(name->>'ar') gin_trgm_ops);

CREATE TRIGGER products_touch BEFORE UPDATE ON catalog.products
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

ALTER TABLE catalog.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE catalog.products FORCE ROW LEVEL SECURITY;

CREATE POLICY products_tenant_isolation ON catalog.products
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

-- ---------------------------------------------------------------------------
-- Product Variants (was product_childerns)
-- ---------------------------------------------------------------------------
CREATE TABLE catalog.product_variants (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id       UUID NOT NULL DEFAULT gen_random_uuid(),
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    product_id      BIGINT NOT NULL REFERENCES catalog.products(id) ON DELETE CASCADE,
    name            JSONB NOT NULL,
    sku             TEXT,
    barcode         TEXT,
    price           NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    cost_price      NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    discount        NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    unit            TEXT,
    image           TEXT,
    status          TEXT NOT NULL DEFAULT 'active'
                    CHECK (status IN ('active','inactive','pending','rejected')),
    is_featured     BOOLEAN NOT NULL DEFAULT false,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at      TIMESTAMPTZ
);

CREATE UNIQUE INDEX product_variants_public_id_key ON catalog.product_variants (public_id);
CREATE INDEX product_variants_org_idx     ON catalog.product_variants (organization_id) WHERE deleted_at IS NULL;
CREATE INDEX product_variants_product_idx ON catalog.product_variants (product_id);
CREATE INDEX product_variants_sku_idx     ON catalog.product_variants (sku) WHERE sku IS NOT NULL;

CREATE TRIGGER product_variants_touch BEFORE UPDATE ON catalog.product_variants
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

ALTER TABLE catalog.product_variants ENABLE ROW LEVEL SECURITY;
ALTER TABLE catalog.product_variants FORCE ROW LEVEL SECURITY;

CREATE POLICY product_variants_tenant_isolation ON catalog.product_variants
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

-- ---------------------------------------------------------------------------
-- Product Metadata and Client Mappings
-- ---------------------------------------------------------------------------
CREATE TABLE catalog.product_infos (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    product_id      BIGINT NOT NULL REFERENCES catalog.products(id) ON DELETE CASCADE,
    key             TEXT NOT NULL,
    value           TEXT NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE catalog.product_infos ENABLE ROW LEVEL SECURITY;
ALTER TABLE catalog.product_infos FORCE ROW LEVEL SECURITY;

CREATE POLICY product_infos_tenant_isolation ON catalog.product_infos
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

CREATE TABLE catalog.product_clients (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    user_id         BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    product_id      BIGINT REFERENCES catalog.products(id) ON DELETE CASCADE,
    name            TEXT NOT NULL,
    price           NUMERIC(12,2),
    discount        NUMERIC(5,2),
    type            TEXT NOT NULL DEFAULT 'sell' CHECK (type IN ('sell','buy')),
    status          TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','processed','rejected')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at      TIMESTAMPTZ
);

ALTER TABLE catalog.product_clients ENABLE ROW LEVEL SECURITY;
ALTER TABLE catalog.product_clients FORCE ROW LEVEL SECURITY;

CREATE POLICY product_clients_tenant_isolation ON catalog.product_clients
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

COMMIT;
