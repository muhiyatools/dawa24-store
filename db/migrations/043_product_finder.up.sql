-- 043_product_finder
--
-- Guided product-finder questionnaire (legacy trees / tree_options /
-- tree_results). A pharmacist answers questions to be walked to the right
-- product.

BEGIN;

CREATE TABLE IF NOT EXISTS catalog.finder_questions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question   JSONB NOT NULL DEFAULT '{"ar":"","en":""}'::JSONB,
    type       TEXT NOT NULL DEFAULT 'choice'
               CHECK (type IN ('choice','text','number')),
    is_first   BOOLEAN NOT NULL DEFAULT false,
    is_active  BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS finder_questions_single_first
    ON catalog.finder_questions ((1)) WHERE is_first AND is_active;

CREATE TABLE IF NOT EXISTS catalog.finder_results (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       JSONB NOT NULL DEFAULT '{"ar":"","en":""}'::JSONB,
    description JSONB NOT NULL DEFAULT '{"ar":"","en":""}'::JSONB
);

CREATE TABLE IF NOT EXISTS catalog.finder_options (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id      BIGINT NOT NULL REFERENCES catalog.finder_questions(id) ON DELETE CASCADE,
    label            JSONB NOT NULL DEFAULT '{"ar":"","en":""}'::JSONB,
    next_question_id BIGINT REFERENCES catalog.finder_questions(id) ON DELETE SET NULL,
    result_id        BIGINT REFERENCES catalog.finder_results(id) ON DELETE SET NULL,
    sort_order       INT NOT NULL DEFAULT 0,
    CHECK (next_question_id IS NOT NULL OR result_id IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS finder_options_question_idx ON catalog.finder_options (question_id, sort_order);

COMMENT ON TABLE catalog.finder_questions IS 'أسئلة دليل اختيار المنتج — guided finder questions';

COMMIT;
