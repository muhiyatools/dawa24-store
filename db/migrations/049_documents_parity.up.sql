-- Migration 049: Documents Parity & Chat Restoration
-- 1. Restores the chat schema so mounted server routes (/messages, /admin/messages) work without error.
-- 2. Expands platform_admin.documents with user ownership, verification workflow, mime_type, file_url and file sizes.

BEGIN;

-- 1. Restore Chat Schema & Tables
CREATE SCHEMA IF NOT EXISTS chat;

CREATE TABLE IF NOT EXISTS chat.conversations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id       UUID NOT NULL DEFAULT gen_random_uuid(),
    title           TEXT NOT NULL DEFAULT '',
    context_type    TEXT NOT NULL DEFAULT 'direct' CHECK (context_type IN ('direct', 'order', 'support', 'quote')),
    context_id      BIGINT,
    organization_id BIGINT REFERENCES org.organizations(id) ON DELETE SET NULL,
    created_by      BIGINT REFERENCES identity.users(id) ON DELETE SET NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at      TIMESTAMPTZ
);

CREATE UNIQUE INDEX IF NOT EXISTS conversations_public_id_key ON chat.conversations (public_id);
CREATE INDEX IF NOT EXISTS conversations_org_idx ON chat.conversations (organization_id) WHERE deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS chat.participants (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES chat.conversations(id) ON DELETE CASCADE,
    user_id         BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    organization_id BIGINT REFERENCES org.organizations(id) ON DELETE SET NULL,
    last_read_at    TIMESTAMPTZ,
    joined_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chat_participant_unique UNIQUE (conversation_id, user_id)
);

CREATE INDEX IF NOT EXISTS chat_participants_user_idx ON chat.participants (user_id);

CREATE TABLE IF NOT EXISTS chat.messages (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id       UUID NOT NULL DEFAULT gen_random_uuid(),
    conversation_id BIGINT NOT NULL REFERENCES chat.conversations(id) ON DELETE CASCADE,
    sender_id       BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    sender_org_id   BIGINT REFERENCES org.organizations(id) ON DELETE SET NULL,
    body            TEXT NOT NULL DEFAULT '',
    attachment_url  TEXT,
    attachment_type TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at      TIMESTAMPTZ
);

CREATE UNIQUE INDEX IF NOT EXISTS messages_public_id_key ON chat.messages (public_id);
CREATE INDEX IF NOT EXISTS messages_conversation_idx ON chat.messages (conversation_id, created_at);

ALTER TABLE chat.conversations ENABLE ROW LEVEL SECURITY;
ALTER TABLE chat.participants ENABLE ROW LEVEL SECURITY;
ALTER TABLE chat.messages ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'chat_conversations_policy') THEN
        CREATE POLICY chat_conversations_policy ON chat.conversations
            USING (true)
            WITH CHECK (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'chat_participants_policy') THEN
        CREATE POLICY chat_participants_policy ON chat.participants
            USING (true)
            WITH CHECK (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'chat_messages_policy') THEN
        CREATE POLICY chat_messages_policy ON chat.messages
            USING (true)
            WITH CHECK (true);
    END IF;
END $$;

-- 2. Expand platform_admin.documents for Full Lifecycle & Review Parity
ALTER TABLE platform_admin.documents
    ADD COLUMN IF NOT EXISTS user_id        BIGINT REFERENCES identity.users(id) ON DELETE CASCADE,
    ADD COLUMN IF NOT EXISTS file_url       TEXT NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS status         TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending','verified','rejected')),
    ADD COLUMN IF NOT EXISTS review_notes   TEXT NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS reviewed_by    BIGINT REFERENCES identity.users(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS reviewed_at    TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS mime_type      TEXT NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS size_bytes     BIGINT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS original_name  TEXT NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS meta           JSONB NOT NULL DEFAULT '{}'::JSONB,
    ADD COLUMN IF NOT EXISTS deleted_at     TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS updated_at     TIMESTAMPTZ NOT NULL DEFAULT now();

CREATE INDEX IF NOT EXISTS documents_org_type_idx  ON platform_admin.documents (organization_id, document_type, status);
CREATE INDEX IF NOT EXISTS documents_user_type_idx ON platform_admin.documents (user_id, document_type, status);

COMMIT;
