-- 125_match_decisions (up)
--
-- Two tables that make matching get cheaper and better the more it is used.
--
-- catalog.match_decisions caches an adjudication: "given this normalised product
-- text and exactly these candidates, the answer was product X". It is what makes
-- re-importing a recurring file nearly free, and it is deliberately **not**
-- tenant-scoped. A decision about catalogue text is a fact about the shared
-- catalogue, identical for every buyer; scoping it per tenant would multiply the
-- cost by the number of buyers and teach the system nothing. It holds no buyer
-- data — only normalised text drawn from the shared catalogue vocabulary — and
-- is read under database.AsSystem with that justification stated at the call
-- site, matching the convention catalog.product_index already uses.
--
-- catalog.product_aliases is the slower, more valuable half: names that have
-- been confirmed to mean a given product. Every confirmed alias is one fewer
-- line that needs adjudicating next time, which is how the AI share of a run
-- shrinks toward zero on files a pharmacy imports every week.
--
-- An alias created from an AI decision starts at source='ai_confirmed' and is
-- only promoted to a full-confidence deterministic tier after a person accepts
-- it. AI output never silently becomes ground truth.

BEGIN;

CREATE TABLE catalog.match_decisions (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    decision_key      TEXT NOT NULL,
    norm_name         TEXT NOT NULL,
    chosen_product_id BIGINT REFERENCES catalog.products(id) ON DELETE CASCADE,
    confidence        NUMERIC(4,3) NOT NULL DEFAULT 0
                      CHECK (confidence >= 0 AND confidence <= 1),
    reason            TEXT,
    prompt_version    TEXT NOT NULL,
    hit_count         BIGINT NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_used_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE  catalog.match_decisions IS 'ذاكرة قرارات المطابقة - معرفة عن الكتالوج المشترك وليست بيانات مشترٍ';
COMMENT ON COLUMN catalog.match_decisions.decision_key IS 'بصمة النص مع قائمة المرشحين ونسخة الطلب - إعادة الاستخدام فقط لنفس السؤال';
COMMENT ON COLUMN catalog.match_decisions.chosen_product_id IS 'فارغ يعني أن الإجابة كانت لا يوجد تطابق - وهي إجابة صحيحة';
COMMENT ON COLUMN catalog.match_decisions.prompt_version IS 'تغييرها يُبطل الذاكرة القديمة دون حذفها';

CREATE UNIQUE INDEX match_decisions_key_uk ON catalog.match_decisions (decision_key);
CREATE INDEX match_decisions_norm_idx      ON catalog.match_decisions (norm_name);
CREATE INDEX match_decisions_last_used_idx ON catalog.match_decisions (last_used_at);

CREATE TABLE catalog.product_aliases (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES catalog.products(id) ON DELETE CASCADE,
    alias      TEXT NOT NULL,
    source     TEXT NOT NULL
               CHECK (source IN ('manual','ai_confirmed','saving_product','import')),
    confidence NUMERIC(4,3) NOT NULL DEFAULT 0
               CHECK (confidence >= 0 AND confidence <= 1),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE  catalog.product_aliases IS 'أسماء بديلة مؤكدة للمنتج - ترفع دقة المطابقة الحتمية مع الوقت';
COMMENT ON COLUMN catalog.product_aliases.source IS 'مصدر الاسم البديل - ai_confirmed لا يُرقّى إلا بقبول بشري';

CREATE UNIQUE INDEX product_aliases_alias_product_uk ON catalog.product_aliases (alias, product_id);
CREATE INDEX product_aliases_product_idx ON catalog.product_aliases (product_id);
CREATE INDEX product_aliases_alias_trgm_idx ON catalog.product_aliases
    USING GIN (alias gin_trgm_ops);

COMMIT;
