-- 010_workflow
--
-- Workflow: Purchase priority engine, weekly branch coverage routes,
-- issue reports, and contact inquiries.

BEGIN;

CREATE SCHEMA IF NOT EXISTS workflow;

-- ---------------------------------------------------------------------------
-- Purchase Priority Engine
-- ---------------------------------------------------------------------------
CREATE TABLE workflow.purchase_priority_engines (
    id                                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id                         UUID NOT NULL DEFAULT gen_random_uuid(),
    user_id                           BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    organization_id                   BIGINT REFERENCES org.organizations(id) ON DELETE CASCADE,
    request_number                    TEXT NOT NULL UNIQUE,
    status                            TEXT NOT NULL DEFAULT 'pending'
                                      CHECK (status IN ('pending','processing','completed','failed')),
    priority_highest_discount         BOOLEAN NOT NULL DEFAULT false,
    priority_lowest_price             BOOLEAN NOT NULL DEFAULT false,
    priority_fastest_delivery         BOOLEAN NOT NULL DEFAULT false,
    priority_preferred_suppliers_only BOOLEAN NOT NULL DEFAULT false,
    budget_constraint                 NUMERIC(12,2),
    parameters                        JSONB NOT NULL DEFAULT '{}'::JSONB,
    recommendations                   JSONB NOT NULL DEFAULT '{}'::JSONB,
    processed_at                      TIMESTAMPTZ,
    created_at                        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at                        TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX purchase_priority_public_id_key ON workflow.purchase_priority_engines (public_id);
CREATE INDEX purchase_priority_user_idx ON workflow.purchase_priority_engines (user_id);

-- ---------------------------------------------------------------------------
-- Weekly Coverage
-- ---------------------------------------------------------------------------
CREATE TABLE workflow.weekly_coverages (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id       UUID NOT NULL DEFAULT gen_random_uuid(),
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    branch_id       BIGINT NOT NULL REFERENCES org.branches(id) ON DELETE CASCADE,
    day_of_week     SMALLINT NOT NULL CHECK (day_of_week BETWEEN 0 AND 6), -- 0 = Sunday
    coverage_from   TIME,
    coverage_to     TIME,
    address         TEXT,
    distance_meters INT NOT NULL DEFAULT 1000,
    is_active       BOOLEAN NOT NULL DEFAULT true,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE workflow.weekly_coverages ENABLE ROW LEVEL SECURITY;
ALTER TABLE workflow.weekly_coverages FORCE ROW LEVEL SECURITY;

CREATE POLICY weekly_coverage_tenant_isolation ON workflow.weekly_coverages
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

-- ---------------------------------------------------------------------------
-- Issue Reports
-- ---------------------------------------------------------------------------
CREATE TABLE workflow.report_issues (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id       UUID NOT NULL DEFAULT gen_random_uuid(),
    reported_by     BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    organization_id BIGINT REFERENCES org.organizations(id) ON DELETE CASCADE,
    order_id        BIGINT REFERENCES commerce.orders(id) ON DELETE SET NULL,
    issue_type      TEXT NOT NULL,
    description     TEXT NOT NULL,
    status          TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','in_progress','resolved')),
    priority        TEXT NOT NULL DEFAULT 'medium' CHECK (priority IN ('low','medium','high')),
    response_notes  TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX report_issues_user_idx ON workflow.report_issues (reported_by);

COMMIT;
