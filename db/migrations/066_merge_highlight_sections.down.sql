-- 066_merge_highlight_sections (down)

BEGIN;

-- 1. Recreate the org family and pull the organization rows back.
CREATE TABLE org.highlight_sections (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    title           JSONB NOT NULL DEFAULT '{"ar":"","en":""}'::JSONB,
    slug            VARCHAR(64) NOT NULL DEFAULT '',
    display_order   INT NOT NULL DEFAULT 0,
    is_active       BOOLEAN NOT NULL DEFAULT true,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX highlight_sections_org_idx ON org.highlight_sections (organization_id, display_order);

CREATE TABLE org.highlight_section_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_id    BIGINT NOT NULL REFERENCES org.highlight_sections(id) ON DELETE CASCADE,
    product_id    BIGINT REFERENCES catalog.products(id) ON DELETE SET NULL,
    offer_id      BIGINT REFERENCES promo.offers(id) ON DELETE SET NULL,
    display_order INT NOT NULL DEFAULT 0,
    CHECK (product_id IS NOT NULL OR offer_id IS NOT NULL)
);

CREATE INDEX highlight_section_items_section_idx ON org.highlight_section_items (section_id, display_order);

INSERT INTO org.highlight_sections (id, organization_id, title, slug, display_order, is_active, created_at, updated_at)
SELECT id, organization_id, title, slug, display_order, is_active, created_at, updated_at
FROM promo.highlight_sections
WHERE owner_type = 'organization';

SELECT setval(pg_get_serial_sequence('org.highlight_sections', 'id'),
              (SELECT COALESCE(MAX(id), 0) + 1 FROM org.highlight_sections), false);

INSERT INTO org.highlight_section_items (id, section_id, product_id, offer_id, display_order)
SELECT i.id, i.section_id, i.product_id, i.offer_id, i.display_order
FROM promo.highlight_section_items i
JOIN org.highlight_sections s ON s.id = i.section_id;

SELECT setval(pg_get_serial_sequence('org.highlight_section_items', 'id'),
              (SELECT COALESCE(MAX(id), 0) + 1 FROM org.highlight_section_items), false);

ALTER TABLE org.highlight_sections ENABLE ROW LEVEL SECURITY;
ALTER TABLE org.highlight_sections FORCE ROW LEVEL SECURITY;

CREATE POLICY highlight_sections_tenant_isolation ON org.highlight_sections
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

ALTER TABLE org.highlight_section_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE org.highlight_section_items FORCE ROW LEVEL SECURITY;

CREATE POLICY highlight_items_via_section ON org.highlight_section_items
    USING (EXISTS (
        SELECT 1 FROM org.highlight_sections s
        WHERE s.id = section_id AND platform.tenant_visible(s.organization_id)
    ))
    WITH CHECK (EXISTS (
        SELECT 1 FROM org.highlight_sections s
        WHERE s.id = section_id AND platform.tenant_visible(s.organization_id)
    ));

-- 2. Strip the merged extras back off the promo table.
ALTER TABLE promo.highlight_section_items
    DROP CONSTRAINT IF EXISTS highlight_section_items_non_empty;

DROP POLICY IF EXISTS highlight_items_via_section ON promo.highlight_section_items;
ALTER TABLE promo.highlight_section_items DISABLE ROW LEVEL SECURITY;
ALTER TABLE promo.highlight_section_items NO FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS highlight_sections_tenant_isolation ON promo.highlight_sections;
ALTER TABLE promo.highlight_sections DISABLE ROW LEVEL SECURITY;
ALTER TABLE promo.highlight_sections NO FORCE ROW LEVEL SECURITY;

DROP INDEX IF EXISTS promo.highlight_sections_platform_slug_key;
ALTER TABLE promo.highlight_sections
    ADD CONSTRAINT highlight_sections_slug_key UNIQUE (slug);

ALTER TABLE promo.highlight_sections
    DROP COLUMN IF EXISTS organization_id,
    DROP COLUMN IF EXISTS owner_type,
    -- The up migration adds updated_at to carry the organization rows'
    -- history; the promo table never had it, so the rollback removes it.
    DROP COLUMN IF EXISTS updated_at;

COMMIT;