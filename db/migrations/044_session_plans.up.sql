-- 044_session_plans
--
-- Concurrent sign-in licensing (legacy session_plans). Purchasing a plan sets
-- identity.user_security.max_login_sessions, which SessionStore.Create already
-- enforces by evicting the oldest session beyond the limit.

BEGIN;

CREATE TABLE IF NOT EXISTS identity.session_plans (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                JSONB NOT NULL DEFAULT '{"ar":"","en":""}'::JSONB,
    max_login_sessions  INT NOT NULL DEFAULT 1,
    price               NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    duration_days       INT NOT NULL DEFAULT 30,
    is_free             BOOLEAN NOT NULL DEFAULT false,
    is_active           BOOLEAN NOT NULL DEFAULT true,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE identity.session_plans IS 'خطط الجلسات المتزامنة — concurrent-session licensing';

COMMIT;
