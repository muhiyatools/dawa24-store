BEGIN;

CREATE TABLE IF NOT EXISTS workflow.automation_requests (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id          UUID NOT NULL DEFAULT gen_random_uuid(),
    user_id            BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    organization_id    BIGINT REFERENCES org.organizations(id) ON DELETE CASCADE,
    request_number     TEXT NOT NULL UNIQUE,
    original_filename  TEXT,
    file_path          TEXT,
    status             TEXT NOT NULL DEFAULT 'pending'
                       CHECK (status IN ('pending', 'processing', 'completed', 'failed', 'approved')),
    total_products     INT NOT NULL DEFAULT 0,
    matched_products   INT NOT NULL DEFAULT 0,
    approved_products  INT NOT NULL DEFAULT 0,
    total_value        NUMERIC(12,2) NOT NULL DEFAULT 0,
    priorities         JSONB NOT NULL DEFAULT '{}'::jsonb,
    budget_constraint  NUMERIC(12,2),
    file_data          JSONB NOT NULL DEFAULT '[]'::jsonb,
    vendor_matches     JSONB NOT NULL DEFAULT '[]'::jsonb,
    comparison_results JSONB NOT NULL DEFAULT '{}'::jsonb,
    notes              TEXT,
    processed_at       TIMESTAMPTZ,
    approved_at        TIMESTAMPTZ,
    approved_by        BIGINT REFERENCES identity.users(id) ON DELETE SET NULL,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS automation_requests_user_idx ON workflow.automation_requests (user_id);
CREATE INDEX IF NOT EXISTS automation_requests_org_idx ON workflow.automation_requests (organization_id);
CREATE INDEX IF NOT EXISTS automation_requests_status_idx ON workflow.automation_requests (status);

ALTER TABLE workflow.automation_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE workflow.automation_requests FORCE ROW LEVEL SECURITY;

CREATE POLICY automation_requests_tenant_isolation ON workflow.automation_requests
    USING (platform.tenant_visible(organization_id) OR user_id = (NULLIF(current_setting('request.jwt.claim.sub', true), ''))::bigint)
    WITH CHECK (platform.tenant_visible(organization_id) OR user_id = (NULLIF(current_setting('request.jwt.claim.sub', true), ''))::bigint);

COMMIT;
