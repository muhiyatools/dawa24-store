-- 003_organizations
--
-- Organizations are the tenant boundary. Every tenant-owned table from here on
-- carries organization_id and enables row-level security against it.
--
-- This migration also establishes the RLS pattern that catalog, inventory,
-- commerce, promo and billing all copy. Read it once, then the rest are
-- mechanical.

BEGIN;

CREATE TABLE org.organizations (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id           UUID NOT NULL DEFAULT gen_random_uuid(),
    organization_number TEXT,
    name                JSONB NOT NULL,
    description         JSONB,
    type                TEXT NOT NULL DEFAULT 'company'
                        CHECK (type IN ('supplier','company','agency')),
    status              TEXT NOT NULL DEFAULT 'pending'
                        CHECK (status IN ('pending','approved','rejected')),
    email               TEXT,
    phone               TEXT,
    address             TEXT,
    tax_number          TEXT,
    image               TEXT,
    coverage_image      TEXT,
    owner_id            BIGINT REFERENCES identity.users(id) ON DELETE SET NULL,
    settings            JSONB NOT NULL DEFAULT '{}'::JSONB,

    -- Money stays NUMERIC, exactly as the legacy DECIMAL(10,2) columns.
    min_order_price     NUMERIC(10,2) NOT NULL DEFAULT 10.00,
    max_order_price     NUMERIC(10,2) NOT NULL DEFAULT 50.00,

    -- Sponsorship, carried over from the offers monetisation engine.
    is_sponsored        BOOLEAN NOT NULL DEFAULT false,
    sponsored_start_at  TIMESTAMPTZ,
    sponsored_end_at    TIMESTAMPTZ,

    -- Legacy stored rating/rank as plain INT with odd defaults (4 and 97).
    -- Values are preserved as-is; recomputing them is a post-cutover concern
    -- and changing them now would break parity comparison against the old UI.
    rating              INT NOT NULL DEFAULT 4,
    rank                INT NOT NULL DEFAULT 97,

    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at          TIMESTAMPTZ,

    CONSTRAINT org_price_range CHECK (max_order_price >= min_order_price),
    CONSTRAINT org_sponsor_window CHECK (
        sponsored_end_at IS NULL OR sponsored_start_at IS NULL
        OR sponsored_end_at > sponsored_start_at
    )
);

CREATE UNIQUE INDEX organizations_public_id_key ON org.organizations (public_id);
CREATE UNIQUE INDEX organizations_number_key    ON org.organizations (organization_number)
    WHERE organization_number IS NOT NULL AND deleted_at IS NULL;
CREATE INDEX organizations_status_idx  ON org.organizations (status) WHERE deleted_at IS NULL;
CREATE INDEX organizations_owner_idx   ON org.organizations (owner_id);
CREATE INDEX organizations_type_idx    ON org.organizations (type) WHERE deleted_at IS NULL;

-- Arabic name search for the vendor directory. The trigram index is built over
-- the normalised form, so diacritics and alif variants match inside the index.
CREATE INDEX organizations_name_trgm_idx ON org.organizations
    USING GIN (platform.normalize_arabic(name->>'ar') gin_trgm_ops);

COMMENT ON TABLE  org.organizations IS 'المؤسسات — suppliers, companies and agencies. The tenant boundary.';
COMMENT ON COLUMN org.organizations.name IS 'اسم المؤسسة أو الشركة // {"ar":"","en":""}';

CREATE TRIGGER organizations_touch BEFORE UPDATE ON org.organizations
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

-- ---------------------------------------------------------------------------
-- Branches
-- ---------------------------------------------------------------------------
CREATE TABLE org.branches (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    name            JSONB NOT NULL,
    phone           TEXT,
    address         TEXT,
    city_id         BIGINT,
    latitude        NUMERIC(10,8),
    longitude       NUMERIC(11,8),
    is_main         BOOLEAN NOT NULL DEFAULT false,
    status          TEXT NOT NULL DEFAULT 'active'
                    CHECK (status IN ('active','inactive')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at      TIMESTAMPTZ
);

CREATE INDEX branches_org_idx  ON org.branches (organization_id) WHERE deleted_at IS NULL;
CREATE INDEX branches_city_idx ON org.branches (city_id);

-- Exactly one main branch per organization. The legacy schema left this
-- unconstrained, so an organization could have zero or three, and the "primary
-- address" shown on an invoice depended on row order.
CREATE UNIQUE INDEX branches_one_main_per_org ON org.branches (organization_id)
    WHERE is_main AND deleted_at IS NULL;

CREATE TRIGGER branches_touch BEFORE UPDATE ON org.branches
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

-- ---------------------------------------------------------------------------
-- Membership
-- ---------------------------------------------------------------------------
CREATE TABLE org.members (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    user_id         BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    branch_id       BIGINT REFERENCES org.branches(id) ON DELETE SET NULL,
    role_key        TEXT NOT NULL REFERENCES identity.roles(key),
    status          TEXT NOT NULL DEFAULT 'active'
                    CHECK (status IN ('active','inactive','suspended','pending')),
    invited_by      BIGINT REFERENCES identity.users(id) ON DELETE SET NULL,
    joined_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),

    UNIQUE (organization_id, user_id)
);

CREATE INDEX members_user_idx   ON org.members (user_id, status);
CREATE INDEX members_org_idx    ON org.members (organization_id, status);
CREATE INDEX members_branch_idx ON org.members (branch_id);

COMMENT ON TABLE org.members IS
    'Membership and organization-scoped role. Replaces legacy organization_users plus the supplier_roles RBAC family.';

CREATE TRIGGER members_touch BEFORE UPDATE ON org.members
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

-- ---------------------------------------------------------------------------
-- Row-level security
-- ---------------------------------------------------------------------------
-- The pattern every tenant-owned table follows.
--
-- FORCE is essential: without it, the table owner (which is often the same role
-- the application connects as in a small deployment) silently bypasses every
-- policy, and the protection is theatre.

ALTER TABLE org.branches ENABLE ROW LEVEL SECURITY;
ALTER TABLE org.branches FORCE ROW LEVEL SECURITY;

CREATE POLICY branches_tenant_isolation ON org.branches
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

ALTER TABLE org.members ENABLE ROW LEVEL SECURITY;
ALTER TABLE org.members FORCE ROW LEVEL SECURITY;

CREATE POLICY members_tenant_isolation ON org.members
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

-- org.organizations itself is deliberately NOT tenant-filtered: the public
-- marketplace lists approved suppliers, and a user must be able to see the
-- organizations they belong to before one is selected as the active tenant.
-- Visibility of an organization's *contents* is what RLS protects.

COMMIT;
