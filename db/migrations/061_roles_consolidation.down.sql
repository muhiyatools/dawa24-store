-- 061_roles_consolidation (down)
--
-- Recreates the dropped tables. org.custom_roles cannot round-trip its rows:
-- they are already merged into org.roles as 'custom_<id>' — the down migration
-- restores the empty table so the schema matches 060, not the data.

BEGIN;

CREATE TABLE IF NOT EXISTS identity.user_roles (
    user_id    BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    role_key   TEXT NOT NULL REFERENCES identity.roles(key) ON DELETE CASCADE,
    granted_by BIGINT REFERENCES identity.users(id) ON DELETE SET NULL,
    granted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, role_key)
);

CREATE TABLE IF NOT EXISTS org.custom_roles (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    name            JSONB NOT NULL,
    description     TEXT NOT NULL DEFAULT '',
    permissions     TEXT[] NOT NULL DEFAULT '{}',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_org_custom_roles_org ON org.custom_roles(organization_id);

DELETE FROM identity.role_permissions
WHERE role_key IN ('org_pharmacist', 'org_sales_rep');

DELETE FROM identity.roles
WHERE key IN ('org_pharmacist', 'org_sales_rep');

COMMENT ON COLUMN org.members.role_key IS NULL;

COMMIT;