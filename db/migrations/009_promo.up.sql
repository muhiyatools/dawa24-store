-- 009_promo
--
-- Promotions, vendor offers, packages, sponsorships, ads, and engagement tracking.

BEGIN;

CREATE SCHEMA IF NOT EXISTS promo;

-- ---------------------------------------------------------------------------
-- Offers & Promotions
-- ---------------------------------------------------------------------------
CREATE TABLE promo.offers (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id       UUID NOT NULL DEFAULT gen_random_uuid(),
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    title           JSONB NOT NULL,
    description     JSONB,
    discount_type   TEXT NOT NULL DEFAULT 'percentage' CHECK (discount_type IN ('percentage','fixed')),
    discount_value  NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    min_order_value NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    starts_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at      TIMESTAMPTZ NOT NULL,
    is_active       BOOLEAN NOT NULL DEFAULT true,
    views_count     BIGINT NOT NULL DEFAULT 0,
    clicks_count    BIGINT NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at      TIMESTAMPTZ
);

CREATE UNIQUE INDEX offers_public_id_key ON promo.offers (public_id);
CREATE INDEX offers_org_idx     ON promo.offers (organization_id) WHERE deleted_at IS NULL;
CREATE INDEX offers_active_idx  ON promo.offers (is_active, starts_at, expires_at) WHERE deleted_at IS NULL;

CREATE TRIGGER offers_touch BEFORE UPDATE ON promo.offers
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

ALTER TABLE promo.offers ENABLE ROW LEVEL SECURITY;
ALTER TABLE promo.offers FORCE ROW LEVEL SECURITY;

CREATE POLICY offers_tenant_isolation ON promo.offers
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

-- ---------------------------------------------------------------------------
-- Offer Products Mapping
-- ---------------------------------------------------------------------------
CREATE TABLE promo.offer_products (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offer_id           BIGINT NOT NULL REFERENCES promo.offers(id) ON DELETE CASCADE,
    product_id         BIGINT NOT NULL REFERENCES catalog.products(id) ON DELETE CASCADE,
    product_variant_id BIGINT REFERENCES catalog.product_variants(id) ON DELETE CASCADE,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX offer_products_offer_idx ON promo.offer_products (offer_id);

-- ---------------------------------------------------------------------------
-- Offer Packages & Sponsorships
-- ---------------------------------------------------------------------------
CREATE TABLE promo.offer_packages (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id     UUID NOT NULL DEFAULT gen_random_uuid(),
    name          JSONB NOT NULL,
    price         NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    duration_days INT NOT NULL DEFAULT 30,
    max_offers    INT NOT NULL DEFAULT 10,
    is_active     BOOLEAN NOT NULL DEFAULT true,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE promo.offer_sponsorships (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id       UUID NOT NULL DEFAULT gen_random_uuid(),
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    offer_id        BIGINT NOT NULL REFERENCES promo.offers(id) ON DELETE CASCADE,
    package_id      BIGINT NOT NULL REFERENCES promo.offer_packages(id) ON DELETE RESTRICT,
    starts_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at      TIMESTAMPTZ NOT NULL,
    status          TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','expired','cancelled')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE promo.offer_sponsorships ENABLE ROW LEVEL SECURITY;
ALTER TABLE promo.offer_sponsorships FORCE ROW LEVEL SECURITY;

CREATE POLICY sponsorships_tenant_isolation ON promo.offer_sponsorships
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

-- ---------------------------------------------------------------------------
-- Advertisements & Tracking
-- ---------------------------------------------------------------------------
CREATE TABLE promo.ads (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id       UUID NOT NULL DEFAULT gen_random_uuid(),
    organization_id BIGINT REFERENCES org.organizations(id) ON DELETE SET NULL,
    title           TEXT NOT NULL,
    image_url       TEXT NOT NULL,
    target_url      TEXT NOT NULL,
    position        TEXT NOT NULL DEFAULT 'home_banner',
    is_active       BOOLEAN NOT NULL DEFAULT true,
    starts_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at      TIMESTAMPTZ NOT NULL,
    impressions     BIGINT NOT NULL DEFAULT 0,
    clicks          BIGINT NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE promo.ad_clicks (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ad_id      BIGINT NOT NULL REFERENCES promo.ads(id) ON DELETE CASCADE,
    user_id    BIGINT REFERENCES identity.users(id) ON DELETE SET NULL,
    ip_address TEXT,
    user_agent TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX ad_clicks_ad_idx ON promo.ad_clicks (ad_id, created_at DESC);

COMMIT;
