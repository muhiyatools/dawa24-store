-- 088_compare_files.up.sql
-- Compare files and parsed rows with archive retention policy and matching storage (Plan V5 Phase 2 Task 2.2).

BEGIN;

-- ---------------------------------------------------------------------------
-- 1. Compare Files (Uploaded Supplier Spreadsheets)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS compare.files (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id           UUID NOT NULL DEFAULT gen_random_uuid(),
    organization_id     BIGINT REFERENCES org.organizations(id) ON DELETE CASCADE,
    user_id             BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    supplier_name       TEXT NOT NULL,
    original_filename   TEXT NOT NULL,
    storage_key         TEXT NOT NULL,
    mime_type           TEXT NOT NULL,
    size_bytes          BIGINT NOT NULL DEFAULT 0,
    row_count           INTEGER NOT NULL DEFAULT 0,
    status              TEXT NOT NULL DEFAULT 'uploaded'
                        CHECK (status IN ('uploaded', 'mapping', 'ready', 'failed', 'archived')),
    mapping_config      JSONB NOT NULL DEFAULT '{}'::jsonb,
    archived_at         TIMESTAMPTZ,
    archive_reason      TEXT,
    error_message       TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at          TIMESTAMPTZ
);

COMMENT ON TABLE compare.files IS 'ملفات جداول الموردين المرفوعة لمحرك مقارنة الخصومات والأسعار';
COMMENT ON COLUMN compare.files.supplier_name IS 'اسم المورد المعين من قبل المستخدم للملف ويمكن تعديله';
COMMENT ON COLUMN compare.files.status IS 'حالة الملف (uploaded, mapping, ready, failed, archived)';

CREATE UNIQUE INDEX IF NOT EXISTS compare_files_public_id_idx ON compare.files (public_id);
CREATE INDEX IF NOT EXISTS compare_files_org_status_idx ON compare.files (organization_id, status) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS compare_files_user_status_idx ON compare.files (user_id, status) WHERE deleted_at IS NULL;

ALTER TABLE compare.files ENABLE ROW LEVEL SECURITY;
ALTER TABLE compare.files FORCE ROW LEVEL SECURITY;

DO $$ BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies 
        WHERE schemaname = 'compare' AND tablename = 'files' AND policyname = 'tenant_isolation_compare_files'
    ) THEN
        CREATE POLICY tenant_isolation_compare_files ON compare.files
            FOR ALL
            USING (organization_id IS NULL OR platform.tenant_visible(organization_id))
            WITH CHECK (organization_id IS NULL OR platform.tenant_visible(organization_id));
    END IF;
END $$;

-- ---------------------------------------------------------------------------
-- 2. Compare File Rows (Parsed Spreadsheet Rows & Matches)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS compare.file_rows (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_id                 BIGINT NOT NULL REFERENCES compare.files(id) ON DELETE CASCADE,
    organization_id         BIGINT REFERENCES org.organizations(id) ON DELETE CASCADE,
    row_number              INTEGER NOT NULL,
    raw_name                TEXT NOT NULL,
    normalized_name         TEXT NOT NULL DEFAULT '',
    sku                     TEXT,
    price                   NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    discount                NUMERIC(5,2) NOT NULL DEFAULT 0.00,
    price_after_discount    NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    matched_product_id      BIGINT REFERENCES catalog.products(id) ON DELETE SET NULL,
    match_confidence        NUMERIC(5,2) NOT NULL DEFAULT 0.00,
    match_method            TEXT NOT NULL DEFAULT 'none'
                            CHECK (match_method IN ('exact', 'sku', 'normalized', 'fuzzy', 'ai', 'manual', 'none')),
    meta                    JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE compare.file_rows IS 'صفوف أصناف الأدوية المستخرجة من ملفات المقارنة مع نتائج التوفيق والأسعار';

CREATE INDEX IF NOT EXISTS compare_file_rows_file_idx ON compare.file_rows (file_id, row_number);
CREATE INDEX IF NOT EXISTS compare_file_rows_org_norm_idx ON compare.file_rows (organization_id, normalized_name);
CREATE INDEX IF NOT EXISTS compare_file_rows_matched_prod_idx ON compare.file_rows (matched_product_id);
CREATE INDEX IF NOT EXISTS compare_file_rows_norm_trgm_idx ON compare.file_rows USING gin (normalized_name gin_trgm_ops);

ALTER TABLE compare.file_rows ENABLE ROW LEVEL SECURITY;
ALTER TABLE compare.file_rows FORCE ROW LEVEL SECURITY;

DO $$ BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies 
        WHERE schemaname = 'compare' AND tablename = 'file_rows' AND policyname = 'tenant_isolation_compare_file_rows'
    ) THEN
        CREATE POLICY tenant_isolation_compare_file_rows ON compare.file_rows
            FOR ALL
            USING (organization_id IS NULL OR platform.tenant_visible(organization_id))
            WITH CHECK (organization_id IS NULL OR platform.tenant_visible(organization_id));
    END IF;
END $$;

COMMIT;
