-- 008_ingest
--
-- Ingest pipeline: Vendor bulk catalog file uploads, import sessions, chunked row
-- staging, column mappings, and matching results.

BEGIN;

CREATE SCHEMA IF NOT EXISTS ingest;

-- ---------------------------------------------------------------------------
-- File Uploads (Object Storage Pointers - D5 Fix)
-- ---------------------------------------------------------------------------
CREATE TABLE ingest.file_uploads (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id       UUID NOT NULL DEFAULT gen_random_uuid(),
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    user_id         BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    filename        TEXT NOT NULL,
    storage_key     TEXT NOT NULL, -- S3 / MinIO key (e.g. orgs/42/imports/file.xlsx)
    file_size_bytes BIGINT NOT NULL,
    mime_type       TEXT NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX file_uploads_public_id_key ON ingest.file_uploads (public_id);
CREATE INDEX file_uploads_org_idx ON ingest.file_uploads (organization_id);

ALTER TABLE ingest.file_uploads ENABLE ROW LEVEL SECURITY;
ALTER TABLE ingest.file_uploads FORCE ROW LEVEL SECURITY;

CREATE POLICY file_uploads_tenant_isolation ON ingest.file_uploads
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

-- ---------------------------------------------------------------------------
-- Import Sessions
-- ---------------------------------------------------------------------------
CREATE TABLE ingest.import_sessions (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id            UUID NOT NULL DEFAULT gen_random_uuid(),
    organization_id      BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    file_upload_id       BIGINT NOT NULL REFERENCES ingest.file_uploads(id) ON DELETE CASCADE,
    status               TEXT NOT NULL DEFAULT 'pending'
                         CHECK (status IN ('pending','processing','completed','failed')),
    column_mapping       JSONB NOT NULL DEFAULT '{}'::JSONB,
    min_similarity_score NUMERIC(3,2) NOT NULL DEFAULT 0.85,
    total_rows           INT NOT NULL DEFAULT 0,
    processed_rows       INT NOT NULL DEFAULT 0,
    matched_rows         INT NOT NULL DEFAULT 0,
    error_message        TEXT,
    started_at           TIMESTAMPTZ,
    completed_at         TIMESTAMPTZ,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX import_sessions_public_id_key ON ingest.import_sessions (public_id);
CREATE INDEX import_sessions_org_idx ON ingest.import_sessions (organization_id);

CREATE TRIGGER import_sessions_touch BEFORE UPDATE ON ingest.import_sessions
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

ALTER TABLE ingest.import_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE ingest.import_sessions FORCE ROW LEVEL SECURITY;

CREATE POLICY import_sessions_tenant_isolation ON ingest.import_sessions
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

-- ---------------------------------------------------------------------------
-- Staged Import Rows
-- ---------------------------------------------------------------------------
CREATE TABLE ingest.import_rows (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id         BIGINT NOT NULL REFERENCES ingest.import_sessions(id) ON DELETE CASCADE,
    organization_id    BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    row_number         INT NOT NULL,
    raw_data           JSONB NOT NULL,
    normalized_name    TEXT,
    matched_product_id BIGINT REFERENCES catalog.products(id) ON DELETE SET NULL,
    similarity_score   NUMERIC(3,2),
    status             TEXT NOT NULL DEFAULT 'pending'
                       CHECK (status IN ('pending','matched','unmatched','imported','rejected')),
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX import_rows_session_idx ON ingest.import_rows (session_id, row_number ASC);
CREATE INDEX import_rows_org_idx     ON ingest.import_rows (organization_id);

ALTER TABLE ingest.import_rows ENABLE ROW LEVEL SECURITY;
ALTER TABLE ingest.import_rows FORCE ROW LEVEL SECURITY;

CREATE POLICY import_rows_tenant_isolation ON ingest.import_rows
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

COMMIT;
