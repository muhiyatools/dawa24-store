-- 012_platform_admin
--
-- Platform Administration: System configurations, localized content, regions, and cities.

BEGIN;

CREATE SCHEMA IF NOT EXISTS platform_admin;

-- ---------------------------------------------------------------------------
-- System Settings
-- ---------------------------------------------------------------------------
CREATE TABLE platform_admin.system_settings (
    key         TEXT PRIMARY KEY,
    value       JSONB NOT NULL,
    description TEXT,
    is_public   BOOLEAN NOT NULL DEFAULT false,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Geographical Data (Countries, Regions, Cities)
-- ---------------------------------------------------------------------------
CREATE TABLE platform_admin.countries (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(3) NOT NULL UNIQUE,
    name       JSONB NOT NULL,
    phone_code VARCHAR(10) NOT NULL,
    currency   VARCHAR(3) NOT NULL DEFAULT 'EGP',
    is_active  BOOLEAN NOT NULL DEFAULT true
);

CREATE TABLE platform_admin.cities (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_id BIGINT NOT NULL REFERENCES platform_admin.countries(id) ON DELETE CASCADE,
    name       JSONB NOT NULL,
    is_active  BOOLEAN NOT NULL DEFAULT true
);

CREATE INDEX cities_country_idx ON platform_admin.cities (country_id);

COMMIT;
