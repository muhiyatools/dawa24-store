CREATE TABLE IF NOT EXISTS assistant.organization_memories (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id              UUID NOT NULL DEFAULT gen_random_uuid(),
    organization_id        BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    user_id                BIGINT REFERENCES identity.users(id) ON DELETE SET NULL,
    scope                  TEXT NOT NULL DEFAULT 'organization' CHECK (scope IN ('organization', 'user')),
    category               TEXT NOT NULL DEFAULT 'general' CHECK (category IN ('business_profile', 'procurement', 'financial', 'logistics', 'preferences', 'contacts', 'general')),
    key                    TEXT NOT NULL DEFAULT '',
    content                TEXT NOT NULL,
    confidence             NUMERIC(3,2) NOT NULL DEFAULT 1.00,
    source                 TEXT NOT NULL DEFAULT 'user_explicit' CHECK (source IN ('user_explicit', 'ai_extracted', 'admin_manual')),
    source_conversation_id BIGINT REFERENCES assistant.conversations(id) ON DELETE SET NULL,
    source_turn_id         BIGINT,
    is_active              BOOLEAN NOT NULL DEFAULT TRUE,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ NOT NULL DEFAULT now()
);

