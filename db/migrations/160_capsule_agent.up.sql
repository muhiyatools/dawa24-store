-- 160_capsule_agent
--
-- Capsule becomes a read-only business agent: it answers from the caller's own
-- authorized data through a tool registry, and it never writes anything.
--
-- Four changes:
--   1. conversations remember which agent produced them, so a user whose role
--      changed cannot resume a conversation built under the old one.
--   2. turns are owned by the server, not by the HTTP request, so an answer
--      survives a dropped connection and can be resumed.
--   3. attachments become rows pointing at object storage, instead of base64
--      living in process memory and in the messages JSONB.
--   4. every tool invocation is audited, allowed or denied.
--
-- Retention: conversations are deleted six months after creation by the worker
-- (assistant.Service.PurgeExpiredConversations). The column here records the
-- deadline so the sweep is an index scan rather than a table scan, and so the
-- UI can state the date rather than a policy.

BEGIN;

-- ---------------------------------------------------------------------------
-- 1. Conversations: agent identity + retention deadline
-- ---------------------------------------------------------------------------

ALTER TABLE assistant.conversations
    ADD COLUMN IF NOT EXISTS agent_role TEXT NOT NULL DEFAULT '';

ALTER TABLE assistant.conversations
    ADD COLUMN IF NOT EXISTS expires_at TIMESTAMPTZ;

COMMENT ON COLUMN assistant.conversations.agent_role IS
    'لوحة التحكم التي أنشأت المحادثة: pharmacy أو vendor أو admin';
COMMENT ON COLUMN assistant.conversations.expires_at IS
    'تاريخ الحذف التلقائي للمحادثة (ستة أشهر من تاريخ الإنشاء)';

-- Backfill the deadline for rows that predate this migration.
UPDATE assistant.conversations
SET expires_at = created_at + INTERVAL '6 months'
WHERE expires_at IS NULL;

ALTER TABLE assistant.conversations
    ALTER COLUMN expires_at SET DEFAULT (now() + INTERVAL '6 months');

CREATE INDEX IF NOT EXISTS idx_assistant_conv_expiry
    ON assistant.conversations (expires_at)
    WHERE deleted_at IS NULL;

-- ---------------------------------------------------------------------------
-- 2. Turns: a unit of work the server owns
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS assistant.turns (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id       UUID NOT NULL DEFAULT gen_random_uuid(),
    conversation_id BIGINT NOT NULL REFERENCES assistant.conversations(id) ON DELETE CASCADE,
    organization_id BIGINT REFERENCES org.organizations(id) ON DELETE CASCADE,
    user_id         BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    agent_role      TEXT NOT NULL DEFAULT '',
    status          TEXT NOT NULL DEFAULT 'running'
                    CHECK (status IN ('running','done','failed','cancelled')),
    question        TEXT NOT NULL DEFAULT '',
    answer          TEXT NOT NULL DEFAULT '',
    error_code      TEXT NOT NULL DEFAULT '',
    input_tokens    INTEGER NOT NULL DEFAULT 0,
    output_tokens   INTEGER NOT NULL DEFAULT 0,
    tool_calls      INTEGER NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at     TIMESTAMPTZ
);

COMMENT ON TABLE assistant.turns IS
    'دورة سؤال/إجابة واحدة يملكها الخادم، حتى لا تضيع الإجابة عند انقطاع الاتصال';

CREATE UNIQUE INDEX IF NOT EXISTS idx_assistant_turn_public ON assistant.turns (public_id);
CREATE INDEX IF NOT EXISTS idx_assistant_turn_conv ON assistant.turns (conversation_id, id DESC);
CREATE INDEX IF NOT EXISTS idx_assistant_turn_running
    ON assistant.turns (user_id, status) WHERE status = 'running';

ALTER TABLE assistant.turns ENABLE ROW LEVEL SECURITY;
ALTER TABLE assistant.turns FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS tenant_isolation_turns ON assistant.turns;
CREATE POLICY tenant_isolation_turns ON assistant.turns
    AS RESTRICTIVE
    USING (platform.is_system() OR (organization_id IS NOT NULL AND platform.tenant_visible(organization_id)))
    WITH CHECK (platform.is_system() OR (organization_id IS NOT NULL AND platform.tenant_visible(organization_id)));

-- ---------------------------------------------------------------------------
-- 3. Attachments: metadata rows, bytes in object storage
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS assistant.attachments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id       UUID NOT NULL DEFAULT gen_random_uuid(),
    organization_id BIGINT REFERENCES org.organizations(id) ON DELETE CASCADE,
    user_id         BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    conversation_id BIGINT REFERENCES assistant.conversations(id) ON DELETE CASCADE,
    filename        TEXT NOT NULL,
    mime_type       TEXT NOT NULL,
    size_bytes      BIGINT NOT NULL DEFAULT 0,
    content_hash    TEXT NOT NULL DEFAULT '',
    storage_key     TEXT NOT NULL DEFAULT '',
    digest          TEXT NOT NULL DEFAULT '',
    referenced      BOOLEAN NOT NULL DEFAULT false,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE assistant.attachments IS
    'مرفقات المساعد الذكي: البيانات في التخزين السحابي وهنا الوصف فقط';
COMMENT ON COLUMN assistant.attachments.digest IS
    'ملخص نصي للملف ينتجه النموذج مرة واحدة ويعاد استخدامه';
COMMENT ON COLUMN assistant.attachments.referenced IS
    'صحيح عندما تربط رسالة محفوظة بهذا المرفق؛ غير المربوط يحذف بعد ٢٤ ساعة';

CREATE UNIQUE INDEX IF NOT EXISTS idx_assistant_att_public ON assistant.attachments (public_id);
CREATE INDEX IF NOT EXISTS idx_assistant_att_owner ON assistant.attachments (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_assistant_att_sweep
    ON assistant.attachments (created_at) WHERE referenced = false;
CREATE INDEX IF NOT EXISTS idx_assistant_att_hash
    ON assistant.attachments (organization_id, content_hash);

ALTER TABLE assistant.attachments ENABLE ROW LEVEL SECURITY;
ALTER TABLE assistant.attachments FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS tenant_isolation_attachments ON assistant.attachments;
CREATE POLICY tenant_isolation_attachments ON assistant.attachments
    AS RESTRICTIVE
    USING (platform.is_system() OR (organization_id IS NOT NULL AND platform.tenant_visible(organization_id)))
    WITH CHECK (platform.is_system() OR (organization_id IS NOT NULL AND platform.tenant_visible(organization_id)));

-- ---------------------------------------------------------------------------
-- 4. Tool audit: what the agent asked for, and what it was allowed
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS assistant.tool_audit (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turn_id         BIGINT REFERENCES assistant.turns(id) ON DELETE CASCADE,
    organization_id BIGINT,
    user_id         BIGINT NOT NULL,
    agent_role      TEXT NOT NULL DEFAULT '',
    tool_name       TEXT NOT NULL,
    decision        TEXT NOT NULL
                    CHECK (decision IN ('allowed','denied_gate','denied_scope','denied_permission',
                                        'denied_handle','invalid_args','unknown_tool','failed')),
    permission      TEXT NOT NULL DEFAULT '',
    latency_ms      INTEGER NOT NULL DEFAULT 0,
    row_count       INTEGER NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE assistant.tool_audit IS
    'سجل كل استدعاء أداة من المساعد الذكي: ما طُلب وما سُمح به ولماذا رُفض';

CREATE INDEX IF NOT EXISTS idx_assistant_audit_turn ON assistant.tool_audit (turn_id);
CREATE INDEX IF NOT EXISTS idx_assistant_audit_denied
    ON assistant.tool_audit (created_at DESC) WHERE decision <> 'allowed';

-- The audit log carries the same isolation as everything else it describes.
--
-- A row with no organisation belongs to platform staff, who have no tenant; it
-- is admitted only under the system flag, which is what the application sets
-- for exactly that case (see assistant/postgres/support.go, ownCtx). A tenant
-- therefore sees only its own refusals, and never learns that another
-- organisation exists from this table.
ALTER TABLE assistant.tool_audit ENABLE ROW LEVEL SECURITY;
ALTER TABLE assistant.tool_audit FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS tenant_isolation_tool_audit ON assistant.tool_audit;
CREATE POLICY tenant_isolation_tool_audit ON assistant.tool_audit
    AS RESTRICTIVE
    USING (platform.is_system() OR (organization_id IS NOT NULL AND platform.tenant_visible(organization_id)))
    WITH CHECK (platform.is_system() OR (organization_id IS NOT NULL AND platform.tenant_visible(organization_id)));

COMMIT;
