-- 147_sponsorship_and_ads
--
-- Sponsorship packages (باقات الرعاية), sponsorship requests (طلبات الرعاية),
-- and enhanced advertisements (الإعلانات) with bilingual content, media,
-- click targets, admin approval, and impression tracking.
--
-- Expand/contract: every change is additive (new columns + new tables). The
-- existing promo.offer_sponsorships table is kept for backward compatibility;
-- the new promo.sponsorship_requests table drives the approval workflow, and
-- approved rows mirror into offer_sponsorships so the ranking query stays one
-- table.

BEGIN;

-- ---------------------------------------------------------------------------
-- 1. Extend promo.offer_packages with tier level, credits, and merchandising.
--    tier_level: higher ranks above lower in sponsored ranking (default 1).
--    credits:    number of products/offers the vendor can sponsor per purchase.
-- ---------------------------------------------------------------------------
ALTER TABLE promo.offer_packages
    ADD COLUMN IF NOT EXISTS tier_level INT NOT NULL DEFAULT 1,
    ADD COLUMN IF NOT EXISTS credits INT NOT NULL DEFAULT 10,
    ADD COLUMN IF NOT EXISTS sort_order INT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS is_featured BOOLEAN NOT NULL DEFAULT false,
    ADD COLUMN IF NOT EXISTS badge_color TEXT NOT NULL DEFAULT '#0284c7',
    ADD COLUMN IF NOT EXISTS description JSONB;

COMMENT ON COLUMN promo.offer_packages.tier_level IS 'مستوى الباقة — الأعلى يظهر في صدارة الترتيب';
COMMENT ON COLUMN promo.offer_packages.credits IS 'عدد الرعايات المتاحة لكل عملية شراء';

CREATE INDEX IF NOT EXISTS idx_offer_packages_tier ON promo.offer_packages (tier_level DESC, sort_order ASC) WHERE is_active = true;

-- ---------------------------------------------------------------------------
-- 2. Sponsorship purchases — tracks a vendor's package purchase and the
--    remaining credits. One row per purchase; credits_used climbs as the
--    vendor submits sponsorship requests against this purchase.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS promo.sponsorship_purchases (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id       UUID NOT NULL DEFAULT gen_random_uuid(),
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    package_id      BIGINT NOT NULL REFERENCES promo.offer_packages(id) ON DELETE RESTRICT,
    credits_total   INT NOT NULL DEFAULT 0,
    credits_used    INT NOT NULL DEFAULT 0,
    starts_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at      TIMESTAMPTZ NOT NULL,
    status          TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','expired','cancelled','pending')),
    auto_renew      BOOLEAN NOT NULL DEFAULT false,
    billing_cycle   TEXT NOT NULL DEFAULT 'monthly',
    amount          NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    payment_id      BIGINT REFERENCES billing.payments(id) ON DELETE SET NULL,
    source_system   TEXT NOT NULL DEFAULT 'wallet_checkout',
    source_id       BIGINT,
    approved_by     BIGINT REFERENCES identity.users(id) ON DELETE SET NULL,
    approved_at     TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT sponsorship_purchases_credits_chk CHECK (credits_used >= 0 AND credits_used <= credits_total)
);

CREATE UNIQUE INDEX IF NOT EXISTS sponsorship_purchases_public_id_key ON promo.sponsorship_purchases (public_id);
CREATE INDEX IF NOT EXISTS idx_sponsorship_purchases_org ON promo.sponsorship_purchases (organization_id) WHERE status = 'active';
CREATE INDEX IF NOT EXISTS idx_sponsorship_purchases_expires ON promo.sponsorship_purchases (expires_at) WHERE status = 'active';

ALTER TABLE promo.sponsorship_purchases ENABLE ROW LEVEL SECURITY;
ALTER TABLE promo.sponsorship_purchases FORCE ROW LEVEL SECURITY;

CREATE POLICY sponsorship_purchases_tenant_isolation ON promo.sponsorship_purchases
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

CREATE TRIGGER sponsorship_purchases_touch BEFORE UPDATE ON promo.sponsorship_purchases
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

-- ---------------------------------------------------------------------------
-- 3. Sponsorship requests — the approval workflow. A vendor submits a request
--    for a product or offer using credits from a purchase. The admin approves
--    or rejects; on approval the row becomes active and the item is ranked.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS promo.sponsorship_requests (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id       UUID NOT NULL DEFAULT gen_random_uuid(),
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    purchase_id     BIGINT REFERENCES promo.sponsorship_purchases(id) ON DELETE SET NULL,
    package_id      BIGINT NOT NULL REFERENCES promo.offer_packages(id) ON DELETE RESTRICT,
    item_type       TEXT NOT NULL DEFAULT 'product' CHECK (item_type IN ('product','offer')),
    item_id         BIGINT NOT NULL,
    credits_used    INT NOT NULL DEFAULT 1,
    admin_status    TEXT NOT NULL DEFAULT 'pending' CHECK (admin_status IN ('pending','approved','rejected')),
    admin_notes     TEXT,
    reviewed_by     BIGINT REFERENCES identity.users(id) ON DELETE SET NULL,
    reviewed_at     TIMESTAMPTZ,
    starts_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at      TIMESTAMPTZ NOT NULL DEFAULT (now() + interval '30 days'),
    status          TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','active','expired','cancelled','rejected')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS sponsorship_requests_public_id_key ON promo.sponsorship_requests (public_id);
CREATE INDEX IF NOT EXISTS idx_sponsorship_requests_org ON promo.sponsorship_requests (organization_id);
CREATE INDEX IF NOT EXISTS idx_sponsorship_requests_admin ON promo.sponsorship_requests (admin_status, status);
CREATE INDEX IF NOT EXISTS idx_sponsorship_requests_active ON promo.sponsorship_requests (item_type, item_id) WHERE status = 'active' AND admin_status = 'approved';

ALTER TABLE promo.sponsorship_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE promo.sponsorship_requests FORCE ROW LEVEL SECURITY;

CREATE POLICY sponsorship_requests_tenant_isolation ON promo.sponsorship_requests
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

CREATE TRIGGER sponsorship_requests_touch BEFORE UPDATE ON promo.sponsorship_requests
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

-- ---------------------------------------------------------------------------
-- 4. Enhanced ads — bilingual content, media (image or video), click targets,
--    admin approval, and impression tracking. The existing columns are kept;
--    new columns are additive.
-- ---------------------------------------------------------------------------
ALTER TABLE promo.ads
    ADD COLUMN IF NOT EXISTS ad_text_ar TEXT,
    ADD COLUMN IF NOT EXISTS ad_text_en TEXT,
    ADD COLUMN IF NOT EXISTS media_type TEXT NOT NULL DEFAULT 'image' CHECK (media_type IN ('image','video')),
    ADD COLUMN IF NOT EXISTS media_url TEXT,
    ADD COLUMN IF NOT EXISTS thumbnail_url TEXT,
    ADD COLUMN IF NOT EXISTS click_target_type TEXT NOT NULL DEFAULT 'vendor_page' CHECK (click_target_type IN ('vendor_page','offer','external_url')),
    ADD COLUMN IF NOT EXISTS click_target_id BIGINT,
    ADD COLUMN IF NOT EXISTS admin_status TEXT NOT NULL DEFAULT 'pending' CHECK (admin_status IN ('pending','approved','rejected')),
    ADD COLUMN IF NOT EXISTS admin_notes TEXT,
    ADD COLUMN IF NOT EXISTS reviewed_by BIGINT REFERENCES identity.users(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS reviewed_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS ad_plan_id BIGINT REFERENCES promo.ad_plans(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS duration_days INT NOT NULL DEFAULT 30,
    ADD COLUMN IF NOT EXISTS title_ar TEXT,
    ADD COLUMN IF NOT EXISTS title_en TEXT;

-- Backfill media_url from image_url so existing ads stay visible.
UPDATE promo.ads SET media_url = image_url WHERE media_url IS NULL AND image_url IS NOT NULL AND image_url <> '';
ALTER TABLE promo.ads ALTER COLUMN media_url SET NOT NULL;

COMMENT ON COLUMN promo.ads.ad_text_ar IS 'النص الإعلاني بالعربية';
COMMENT ON COLUMN promo.ads.ad_text_en IS 'Advertising text in English';
COMMENT ON COLUMN promo.ads.media_type IS 'نوع الوسائط: صورة أو فيديو';
COMMENT ON COLUMN promo.ads.click_target_type IS 'وجهة النقر: صفحة المورد أو عرض معين';

CREATE INDEX IF NOT EXISTS idx_ads_admin_status ON promo.ads (admin_status, is_active, expires_at);
CREATE INDEX IF NOT EXISTS idx_ads_position_active ON promo.ads (position) WHERE is_active = true AND admin_status = 'approved';

-- Ad impressions (views) tracking — parallel to ad_clicks.
CREATE TABLE IF NOT EXISTS promo.ad_impressions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ad_id      BIGINT NOT NULL REFERENCES promo.ads(id) ON DELETE CASCADE,
    user_id    BIGINT REFERENCES identity.users(id) ON DELETE SET NULL,
    ip_address TEXT,
    user_agent TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_ad_impressions_ad ON promo.ad_impressions (ad_id, created_at DESC);

-- ---------------------------------------------------------------------------
-- 5. Extend promo.offer_sponsorships with the approval workflow columns so
--    existing sponsorships and new approved requests share the same shape.
-- ---------------------------------------------------------------------------
ALTER TABLE promo.offer_sponsorships
    ADD COLUMN IF NOT EXISTS item_type TEXT NOT NULL DEFAULT 'offer' CHECK (item_type IN ('product','offer')),
    ADD COLUMN IF NOT EXISTS item_id BIGINT,
    ADD COLUMN IF NOT EXISTS credits_used INT NOT NULL DEFAULT 1,
    ADD COLUMN IF NOT EXISTS admin_status TEXT NOT NULL DEFAULT 'approved' CHECK (admin_status IN ('pending','approved','rejected')),
    ADD COLUMN IF NOT EXISTS admin_notes TEXT,
    ADD COLUMN IF NOT EXISTS reviewed_by BIGINT REFERENCES identity.users(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS reviewed_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS sponsorship_request_id BIGINT REFERENCES promo.sponsorship_requests(id) ON DELETE SET NULL;

-- Backfill item_id from offer_id for existing rows.
UPDATE promo.offer_sponsorships SET item_id = offer_id WHERE item_id IS NULL;

CREATE INDEX IF NOT EXISTS idx_offer_sponsorships_active ON promo.offer_sponsorships (item_type, item_id) WHERE status = 'active' AND admin_status = 'approved';

COMMIT;
