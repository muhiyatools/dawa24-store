-- 020_platform_extensions
--
-- Currencies, Languages, Contact Inquiries, and Organization Document Registry.

BEGIN;

CREATE TABLE platform_admin.currencies (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                TEXT NOT NULL UNIQUE,
    name                JSONB NOT NULL,
    symbol              TEXT NOT NULL,
    exchange_rate_egp   NUMERIC(12,4) NOT NULL DEFAULT 1.0000,
    is_active           BOOLEAN NOT NULL DEFAULT true,
    is_default          BOOLEAN NOT NULL DEFAULT false,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE platform_admin.languages (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       TEXT NOT NULL UNIQUE,
    name       TEXT NOT NULL,
    dir        TEXT NOT NULL DEFAULT 'rtl' CHECK (dir IN ('rtl','ltr')),
    is_active  BOOLEAN NOT NULL DEFAULT true,
    is_default BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE platform_admin.contact_messages (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id  UUID NOT NULL DEFAULT gen_random_uuid(),
    name       TEXT NOT NULL,
    email      TEXT NOT NULL,
    phone      TEXT,
    subject    TEXT NOT NULL,
    message    TEXT NOT NULL,
    status     TEXT NOT NULL DEFAULT 'unread' CHECK (status IN ('unread','read','resolved')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX contact_messages_status_idx ON platform_admin.contact_messages (status, created_at DESC);

CREATE TABLE platform_admin.documents (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id       UUID NOT NULL DEFAULT gen_random_uuid(),
    organization_id BIGINT REFERENCES org.organizations(id) ON DELETE CASCADE,
    title           TEXT NOT NULL,
    document_type   TEXT NOT NULL,
    storage_key     TEXT NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX documents_org_idx ON platform_admin.documents (organization_id);

COMMIT;
