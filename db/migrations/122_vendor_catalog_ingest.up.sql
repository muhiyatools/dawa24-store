-- 122_vendor_catalog_ingest (up)
--
-- Staging for the vendor catalogue import.
--
-- ingest.import_sessions and ingest.import_rows stage the old vendor importer:
-- every spreadsheet row is written into the database as raw JSON before
-- anything is known about it, and the mapping is a flat field→header-name map
-- that cannot express a confidence, a conflict, or two columns sharing a title.
-- Neither shape survives the rewrite, and neither is altered here: the old
-- tables stay until the code that reads them is removed, so a deployment can
-- roll back to the previous image without losing an in-flight import.
--
-- The new shape stages the *decisions* rather than the data. The uploaded file
-- lives on the session, the confirmed mapping and settings live beside it, and
-- the rows are streamed out of the file at processing time rather than being
-- copied into Postgres first. A nine-thousand-row workbook therefore costs one
-- row here and 350 KB of bytea, not nine thousand JSON documents.

BEGIN;

CREATE TABLE IF NOT EXISTS ingest.catalog_imports (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id         UUID NOT NULL DEFAULT gen_random_uuid(),
    organization_id   BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    created_by        BIGINT REFERENCES identity.users(id) ON DELETE SET NULL,

    filename          TEXT NOT NULL DEFAULT '',
    file_size_bytes   BIGINT NOT NULL DEFAULT 0,
    -- The bytes, kept so the mapping can be corrected and the file re-read
    -- without asking the vendor to upload it again. Stored on the row rather
    -- than in object storage for the same reasons as the admin importer: these
    -- files are small, they are reaped with the session, and the import has to
    -- work on a deployment with no bucket configured.
    source_file       BYTEA NOT NULL DEFAULT ''::BYTEA,

    -- The stage the vendor has reached. It is the screen's own state, not a job
    -- status: 'mapping' is waiting for them, 'processing' is waiting for us.
    phase             TEXT NOT NULL DEFAULT 'mapping'
                      CHECK (phase IN ('mapping','settings','confirm','processing','completed','failed','cancelled')),

    -- How the file decoded, what the vendor corrected, what they chose, and
    -- what the engine finally resolved. Documents rather than columns because
    -- each is read and written whole and only by this feature.
    source            JSONB NOT NULL DEFAULT '{}'::JSONB,
    overrides         JSONB NOT NULL DEFAULT '{}'::JSONB,
    settings          JSONB NOT NULL DEFAULT '{}'::JSONB,
    mapping           JSONB NOT NULL DEFAULT '{}'::JSONB,
    stats             JSONB NOT NULL DEFAULT '{}'::JSONB,
    findings          JSONB NOT NULL DEFAULT '[]'::JSONB,

    total_rows        INT NOT NULL DEFAULT 0,
    inserted_rows     INT NOT NULL DEFAULT 0,
    updated_rows      INT NOT NULL DEFAULT 0,
    skipped_rows      INT NOT NULL DEFAULT 0,
    error_rows        INT NOT NULL DEFAULT 0,
    matched_rows      INT NOT NULL DEFAULT 0,
    review_rows       INT NOT NULL DEFAULT 0,
    unmatched_rows    INT NOT NULL DEFAULT 0,
    created_products  INT NOT NULL DEFAULT 0,

    progress_percent  INT NOT NULL DEFAULT 0,
    progress_note     TEXT NOT NULL DEFAULT '',
    error_message     TEXT NOT NULL DEFAULT '',

    started_at        TIMESTAMPTZ,
    completed_at      TIMESTAMPTZ,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- An abandoned review holds a copy of the vendor's file. Without an expiry
    -- the table grows without bound; the sweep runs when a new import is
    -- opened, so no scheduled job is needed to collect them.
    expires_at        TIMESTAMPTZ NOT NULL DEFAULT now() + INTERVAL '24 hours'
);

CREATE UNIQUE INDEX IF NOT EXISTS catalog_imports_public_id_key
    ON ingest.catalog_imports (public_id);
CREATE INDEX IF NOT EXISTS catalog_imports_org_created
    ON ingest.catalog_imports (organization_id, created_at DESC);
CREATE INDEX IF NOT EXISTS catalog_imports_expiry
    ON ingest.catalog_imports (expires_at)
    WHERE phase IN ('mapping','settings','confirm');

CREATE TRIGGER catalog_imports_touch BEFORE UPDATE ON ingest.catalog_imports
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

-- The per-row outcome ledger.
--
-- Written during processing, one row per spreadsheet line, so the results
-- screen can be filtered and paged and so an unmatched line can be exported,
-- corrected and re-uploaded. It is deliberately an *outcome* record and not a
-- staging record: nothing here is read back to decide what to write.
CREATE TABLE IF NOT EXISTS ingest.catalog_import_rows (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_id       BIGINT NOT NULL REFERENCES ingest.catalog_imports(id) ON DELETE CASCADE,
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    -- The row number in the vendor's own spreadsheet, one-based, so a finding
    -- points at a line they can open and look at.
    source_row      INT NOT NULL DEFAULT 0,

    outcome         TEXT NOT NULL DEFAULT 'skipped'
                    CHECK (outcome IN ('inserted','updated','skipped','error')),
    match_level     TEXT NOT NULL DEFAULT 'none',
    match_score     NUMERIC(5,4) NOT NULL DEFAULT 0,

    product_id      BIGINT REFERENCES catalog.products(id) ON DELETE SET NULL,
    variant_id      BIGINT REFERENCES catalog.product_variants(id) ON DELETE SET NULL,

    display_name    TEXT NOT NULL DEFAULT '',
    source_code     TEXT NOT NULL DEFAULT '',
    payload         JSONB NOT NULL DEFAULT '{}'::JSONB,
    candidates      JSONB NOT NULL DEFAULT '[]'::JSONB,
    issues          JSONB NOT NULL DEFAULT '[]'::JSONB,
    message         TEXT NOT NULL DEFAULT '',

    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS catalog_import_rows_import
    ON ingest.catalog_import_rows (import_id, source_row);
CREATE INDEX IF NOT EXISTS catalog_import_rows_outcome
    ON ingest.catalog_import_rows (import_id, outcome);
CREATE INDEX IF NOT EXISTS catalog_import_rows_match
    ON ingest.catalog_import_rows (import_id, match_level);

-- Tenant isolation. FORCE matters: without it the table owner — often the same
-- role the application connects as — bypasses every policy silently.
ALTER TABLE ingest.catalog_imports ENABLE ROW LEVEL SECURITY;
ALTER TABLE ingest.catalog_imports FORCE ROW LEVEL SECURITY;
CREATE POLICY catalog_imports_tenant_isolation ON ingest.catalog_imports
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

ALTER TABLE ingest.catalog_import_rows ENABLE ROW LEVEL SECURITY;
ALTER TABLE ingest.catalog_import_rows FORCE ROW LEVEL SECURITY;
CREATE POLICY catalog_import_rows_tenant_isolation ON ingest.catalog_import_rows
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

COMMENT ON TABLE ingest.catalog_imports IS
    'جلسات استيراد كتالوج المورد — تحليل الملف ومراجعة الربط والإعدادات قبل التنفيذ';
COMMENT ON COLUMN ingest.catalog_imports.source_file IS
    'الملف المرفوع، محفوظ مؤقتاً لإعادة القراءة بعد تعديل الربط، ويُحذف مع انتهاء صلاحية الجلسة';
COMMENT ON COLUMN ingest.catalog_imports.mapping IS
    'ربط الأعمدة النهائي الذي اعتمده المورد، بما فيه درجة الثقة وسبب كل ربط';
COMMENT ON TABLE ingest.catalog_import_rows IS
    'سجل نتيجة كل صف بعد التنفيذ: ما تم إدخاله أو تحديثه أو تخطيه ولماذا';

COMMIT;
