-- 070_merge_file_uploads (down)
--
-- Recreate ingest.file_uploads with its RLS, move import-file documents back,
-- and restore the FK. At rollback time every 'import_file' row came from this
-- migration, so the move is exact.

BEGIN;

CREATE TABLE ingest.file_uploads (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id       UUID NOT NULL DEFAULT gen_random_uuid(),
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    user_id         BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    filename        TEXT NOT NULL,
    storage_key     TEXT NOT NULL,
    file_size_bytes BIGINT NOT NULL,
    mime_type       TEXT NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX file_uploads_public_id_key ON ingest.file_uploads (public_id);
CREATE INDEX file_uploads_org_idx ON ingest.file_uploads (organization_id);

ALTER TABLE ingest.file_uploads ENABLE ROW LEVEL SECURITY;
ALTER TABLE ingest.file_uploads FORCE ROW LEVEL SECURITY;

CREATE POLICY file_uploads_tenant_isolation ON ingest.file_uploads
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

INSERT INTO ingest.file_uploads (public_id, organization_id, user_id, filename, storage_key, file_size_bytes, mime_type, created_at)
SELECT public_id, organization_id, user_id, original_name, storage_key, size_bytes, mime_type, created_at
FROM platform_admin.documents
WHERE document_type = 'import_file';

DELETE FROM platform_admin.documents WHERE document_type = 'import_file';

ALTER TABLE ingest.import_sessions
    DROP CONSTRAINT IF EXISTS import_sessions_file_upload_id_fkey;

ALTER TABLE ingest.import_sessions
    ADD CONSTRAINT import_sessions_file_upload_id_fkey
    FOREIGN KEY (file_upload_id) REFERENCES ingest.file_uploads(id) ON DELETE CASCADE;

COMMIT;
