-- 006_commerce
--
-- Commerce: Shopping carts, orders, vendor shipment splits, line item snapshots,
-- and immutable order state history.

BEGIN;

CREATE SCHEMA IF NOT EXISTS commerce;

-- ---------------------------------------------------------------------------
-- Shopping Carts
-- ---------------------------------------------------------------------------
CREATE TABLE commerce.carts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id       UUID NOT NULL DEFAULT gen_random_uuid(),
    user_id         BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    organization_id BIGINT REFERENCES org.organizations(id) ON DELETE SET NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT carts_user_unique UNIQUE (user_id)
);

CREATE UNIQUE INDEX carts_public_id_key ON commerce.carts (public_id);
CREATE INDEX carts_user_idx ON commerce.carts (user_id);

CREATE TRIGGER carts_touch BEFORE UPDATE ON commerce.carts
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

CREATE TABLE commerce.cart_items (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id            BIGINT NOT NULL REFERENCES commerce.carts(id) ON DELETE CASCADE,
    product_id         BIGINT NOT NULL REFERENCES catalog.products(id) ON DELETE CASCADE,
    product_variant_id BIGINT NOT NULL REFERENCES catalog.product_variants(id) ON DELETE CASCADE,
    quantity           INT NOT NULL CHECK (quantity > 0),
    unit_price         NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT cart_items_variant_unique UNIQUE (cart_id, product_variant_id)
);

CREATE INDEX cart_items_cart_idx ON commerce.cart_items (cart_id);

CREATE TRIGGER cart_items_touch BEFORE UPDATE ON commerce.cart_items
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

-- ---------------------------------------------------------------------------
-- Master Customer Orders
-- ---------------------------------------------------------------------------
CREATE TABLE commerce.orders (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id        UUID NOT NULL DEFAULT gen_random_uuid(),
    order_number     TEXT NOT NULL,
    customer_id      BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE RESTRICT,
    organization_id  BIGINT REFERENCES org.organizations(id) ON DELETE SET NULL,
    status           TEXT NOT NULL DEFAULT 'pending'
                     CHECK (status IN ('pending','confirmed','processing','ready_for_pickup','shipped','delivered','cancelled','refunded')),
    subtotal         NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    discount_amount  NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    shipping_fee     NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    tax_amount       NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    total_amount     NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    shipping_address JSONB NOT NULL DEFAULT '{}'::JSONB,
    payment_method   TEXT NOT NULL DEFAULT 'cash_on_delivery',
    payment_status   TEXT NOT NULL DEFAULT 'unpaid'
                     CHECK (payment_status IN ('unpaid','authorized','paid','partially_refunded','refunded','failed')),
    notes            TEXT,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at       TIMESTAMPTZ
);

CREATE UNIQUE INDEX orders_public_id_key ON commerce.orders (public_id);
CREATE UNIQUE INDEX orders_order_number_key ON commerce.orders (order_number);
CREATE INDEX orders_customer_idx ON commerce.orders (customer_id);
CREATE INDEX orders_org_idx      ON commerce.orders (organization_id) WHERE organization_id IS NOT NULL;
CREATE INDEX orders_status_idx   ON commerce.orders (status);

CREATE TRIGGER orders_touch BEFORE UPDATE ON commerce.orders
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

ALTER TABLE commerce.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE commerce.orders FORCE ROW LEVEL SECURITY;

CREATE POLICY orders_tenant_isolation ON commerce.orders
    USING (organization_id IS NULL OR platform.tenant_visible(organization_id))
    WITH CHECK (organization_id IS NULL OR platform.tenant_visible(organization_id));

-- ---------------------------------------------------------------------------
-- Vendor Shipment Splits (Orders per Vendor)
-- ---------------------------------------------------------------------------
CREATE TABLE commerce.order_shipments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id       UUID NOT NULL DEFAULT gen_random_uuid(),
    order_id        BIGINT NOT NULL REFERENCES commerce.orders(id) ON DELETE CASCADE,
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE RESTRICT,
    branch_id       BIGINT REFERENCES org.branches(id) ON DELETE SET NULL,
    shipment_number TEXT NOT NULL,
    status          TEXT NOT NULL DEFAULT 'pending'
                    CHECK (status IN ('pending','confirmed','processing','ready_for_pickup','shipped','delivered','cancelled','returned')),
    subtotal        NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    shipping_fee    NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    total_amount    NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    tracking_number TEXT,
    carrier_name    TEXT,
    shipped_at      TIMESTAMPTZ,
    delivered_at    TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX order_shipments_public_id_key ON commerce.order_shipments (public_id);
CREATE UNIQUE INDEX order_shipments_number_key ON commerce.order_shipments (shipment_number);
CREATE INDEX order_shipments_order_idx ON commerce.order_shipments (order_id);
CREATE INDEX order_shipments_org_idx   ON commerce.order_shipments (organization_id);

CREATE TRIGGER order_shipments_touch BEFORE UPDATE ON commerce.order_shipments
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

ALTER TABLE commerce.order_shipments ENABLE ROW LEVEL SECURITY;
ALTER TABLE commerce.order_shipments FORCE ROW LEVEL SECURITY;

CREATE POLICY order_shipments_tenant_isolation ON commerce.order_shipments
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

-- ---------------------------------------------------------------------------
-- Order Line Items (Immutable Snapshots)
-- ---------------------------------------------------------------------------
CREATE TABLE commerce.order_lines (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id           BIGINT NOT NULL REFERENCES commerce.orders(id) ON DELETE CASCADE,
    shipment_id        BIGINT NOT NULL REFERENCES commerce.order_shipments(id) ON DELETE CASCADE,
    organization_id    BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE RESTRICT,
    product_id         BIGINT REFERENCES catalog.products(id) ON DELETE SET NULL,
    product_variant_id BIGINT REFERENCES catalog.product_variants(id) ON DELETE SET NULL,
    product_name       JSONB NOT NULL,
    variant_name       JSONB,
    sku                TEXT,
    unit_price         NUMERIC(12,2) NOT NULL,
    quantity           INT NOT NULL CHECK (quantity > 0),
    discount_amount    NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    total_price        NUMERIC(12,2) NOT NULL,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX order_lines_order_idx    ON commerce.order_lines (order_id);
CREATE INDEX order_lines_shipment_idx ON commerce.order_lines (shipment_id);
CREATE INDEX order_lines_org_idx      ON commerce.order_lines (organization_id);

ALTER TABLE commerce.order_lines ENABLE ROW LEVEL SECURITY;
ALTER TABLE commerce.order_lines FORCE ROW LEVEL SECURITY;

CREATE POLICY order_lines_tenant_isolation ON commerce.order_lines
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

-- ---------------------------------------------------------------------------
-- Order State Change Audit History
-- ---------------------------------------------------------------------------
CREATE TABLE commerce.order_status_history (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id           BIGINT NOT NULL REFERENCES commerce.orders(id) ON DELETE CASCADE,
    shipment_id        BIGINT REFERENCES commerce.order_shipments(id) ON DELETE CASCADE,
    from_status        TEXT,
    to_status          TEXT NOT NULL,
    notes              TEXT,
    changed_by_user_id BIGINT REFERENCES identity.users(id) ON DELETE SET NULL,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX order_history_order_idx    ON commerce.order_status_history (order_id, created_at DESC);
CREATE INDEX order_history_shipment_idx ON commerce.order_status_history (shipment_id, created_at DESC);

COMMIT;
