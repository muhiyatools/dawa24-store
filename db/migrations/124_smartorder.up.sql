-- 124_smartorder (up)
--
-- Smart Ordering (نظام الطلب الذكي) — specs/001-smart-ordering-system.
--
-- A pharmacy uploads a spreadsheet of what it needs; the system resolves every
-- row to a catalogue product, enumerates the vendor variants of that product,
-- filters them through coverage and Corporate Operations, chooses one supplier
-- per line under the buyer's criteria, and hands back an order to review.
--
-- Shape notes, because two of these look redundant and are not:
--
--   * run_config is a separate table rather than columns on runs because it is
--     a *snapshot*. The buyer's saved defaults live in criteria_profiles and
--     change freely; a finished run must still be able to explain why it chose
--     what it chose, which means the configuration it ran under cannot move
--     underneath it.
--
--   * line_candidates keeps the vendors it *rejected*, with the reason. The
--     buyer's first question about any line is "why not that supplier", and
--     recomputing the answer means re-running coverage against a clock that has
--     since moved. Storing it is cheaper and honest.
--
-- Money is NUMERIC(12,2) throughout and is read into money.Amount. The one
-- exception is runs.ai_cost_estimate, which is NUMERIC(12,6) USD telemetry and
-- deliberately not money.Amount: that type is EGP minor units for commerce.

BEGIN;

CREATE SCHEMA IF NOT EXISTS smartorder;

-- Run numbers are human-facing (SO-2026-000142) and must not collide. A
-- sequence rather than a count(*) or a max()+1: those race under concurrent
-- imports, and two runs sharing a number is the kind of defect that only shows
-- up when two branches of the same pharmacy upload at once.
CREATE SEQUENCE IF NOT EXISTS smartorder.run_number_seq;

-- ---------------------------------------------------------------------------
-- Runs — one end-to-end execution
-- ---------------------------------------------------------------------------
CREATE TABLE smartorder.runs (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id                  UUID NOT NULL DEFAULT gen_random_uuid(),
    run_number                 TEXT NOT NULL,
    organization_id            BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    user_id                    BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    branch_id                  BIGINT NOT NULL REFERENCES org.branches(id) ON DELETE RESTRICT,
    upload_id                  BIGINT,
    original_filename          TEXT,

    status                     TEXT NOT NULL DEFAULT 'draft'
                               CHECK (status IN ('draft','mapping','queued','processing',
                                                 'completed','stale','finalizing','placed','failed')),
    current_step               SMALLINT NOT NULL DEFAULT 1 CHECK (current_step BETWEEN 1 AND 5),

    total_rows                 INT NOT NULL DEFAULT 0,
    matched_rows               INT NOT NULL DEFAULT 0,
    unmatched_rows             INT NOT NULL DEFAULT 0,
    no_supplier_rows           INT NOT NULL DEFAULT 0,
    coverage_blocked_rows      INT NOT NULL DEFAULT 0,
    institutional_blocked_rows INT NOT NULL DEFAULT 0,
    below_min_qty_rows         INT NOT NULL DEFAULT 0,

    estimated_total            NUMERIC(12,2) NOT NULL DEFAULT 0,
    budget_exceeded            BOOLEAN,
    budget_overage             NUMERIC(12,2),

    order_id                   BIGINT REFERENCES commerce.orders(id) ON DELETE SET NULL,
    finalized_at               TIMESTAMPTZ,

    ai_enabled                 BOOLEAN NOT NULL DEFAULT false,
    ai_calls                   INT NOT NULL DEFAULT 0,
    ai_lines_adjudicated       INT NOT NULL DEFAULT 0,
    ai_cost_estimate           NUMERIC(12,6) NOT NULL DEFAULT 0,
    ai_ceiling_hit             BOOLEAN NOT NULL DEFAULT false,

    deterministic_ms           INT,
    total_ms                   INT,
    failure_reason             TEXT,

    created_at                 TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at                 TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE  smartorder.runs IS 'الطلب الذكي - تنفيذ كامل من رفع الملف حتى الطلب';
COMMENT ON COLUMN smartorder.runs.branch_id IS 'الفرع - عنوان التسليم، وموقعه هو ما تُقاس عليه التغطية';
COMMENT ON COLUMN smartorder.runs.budget_exceeded IS 'تجاوز الميزانية - للعرض فقط، لا يمنع الطلب';
COMMENT ON COLUMN smartorder.runs.finalized_at IS 'وقت اعتماد الطلب - وجوده يمنع الاعتماد مرة أخرى';
COMMENT ON COLUMN smartorder.runs.ai_ceiling_hit IS 'تم بلوغ حد الذكاء الاصطناعي وتوقفت المطابقة الإضافية';
COMMENT ON COLUMN smartorder.runs.ai_cost_estimate IS 'تقدير التكلفة بالدولار - قياس تشغيلي وليس مبلغًا تجاريًا';

CREATE UNIQUE INDEX runs_public_id_key  ON smartorder.runs (public_id);
CREATE UNIQUE INDEX runs_run_number_key ON smartorder.runs (run_number);
CREATE INDEX runs_org_created_idx ON smartorder.runs (organization_id, created_at DESC);
CREATE INDEX runs_status_idx      ON smartorder.runs (status);
CREATE INDEX runs_user_idx        ON smartorder.runs (user_id);

CREATE TRIGGER runs_touch BEFORE UPDATE ON smartorder.runs
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

ALTER TABLE smartorder.runs ENABLE ROW LEVEL SECURITY;
ALTER TABLE smartorder.runs FORCE ROW LEVEL SECURITY;
CREATE POLICY runs_tenant_isolation ON smartorder.runs
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

-- ---------------------------------------------------------------------------
-- Run configuration — the snapshot the run actually executed under
-- ---------------------------------------------------------------------------
CREATE TABLE smartorder.run_config (
    run_id              BIGINT PRIMARY KEY REFERENCES smartorder.runs(id) ON DELETE CASCADE,
    organization_id     BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    criteria            JSONB NOT NULL DEFAULT '[]'::JSONB,
    tolerance_pct       NUMERIC(5,2) NOT NULL DEFAULT 5.00 CHECK (tolerance_pct >= 0 AND tolerance_pct <= 100),
    default_quantity    INT NOT NULL DEFAULT 0 CHECK (default_quantity >= 0),
    max_budget          NUMERIC(12,2) CHECK (max_budget IS NULL OR max_budget > 0),
    use_saving_products BOOLEAN NOT NULL DEFAULT false,
    use_ai_matching     BOOLEAN NOT NULL DEFAULT false,
    criteria_defaulted  BOOLEAN NOT NULL DEFAULT false,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE  smartorder.run_config IS 'إعدادات الطلب وقت التنفيذ - لقطة ثابتة حتى تظل النتائج قابلة للتفسير';
COMMENT ON COLUMN smartorder.run_config.criteria IS 'معايير اختيار الموردين مرتبة حسب الأولوية';
COMMENT ON COLUMN smartorder.run_config.tolerance_pct IS 'نطاق التسامح - نسبة فوق أقل سعر صافٍ يُقبل داخلها المعيار الأعلى';
COMMENT ON COLUMN smartorder.run_config.default_quantity IS 'الكمية الافتراضية - تُطبق فقط على الصفوف بلا كمية';
COMMENT ON COLUMN smartorder.run_config.criteria_defaulted IS 'لم يفعّل المشتري أي معيار فطُبق الترتيب الافتراضي';

ALTER TABLE smartorder.run_config ENABLE ROW LEVEL SECURITY;
ALTER TABLE smartorder.run_config FORCE ROW LEVEL SECURITY;
CREATE POLICY run_config_tenant_isolation ON smartorder.run_config
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

-- ---------------------------------------------------------------------------
-- Column mappings
-- ---------------------------------------------------------------------------
CREATE TABLE smartorder.column_mappings (
    run_id          BIGINT PRIMARY KEY REFERENCES smartorder.runs(id) ON DELETE CASCADE,
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    header_row      INT NOT NULL DEFAULT 0 CHECK (header_row >= 0),
    mapping         JSONB NOT NULL DEFAULT '{}'::JSONB,
    detected        JSONB NOT NULL DEFAULT '{}'::JSONB,
    confidence      JSONB NOT NULL DEFAULT '{}'::JSONB,
    user_overridden BOOLEAN NOT NULL DEFAULT false,
    confirmed_at    TIMESTAMPTZ
);

COMMENT ON TABLE  smartorder.column_mappings IS 'ربط أعمدة الملف بالحقول';
COMMENT ON COLUMN smartorder.column_mappings.detected IS 'التخمين التلقائي - يُحفظ للمقارنة مع تعديل المستخدم';
COMMENT ON COLUMN smartorder.column_mappings.header_row IS 'صف العناوين الحقيقي بعد تخطي صفوف الترويسة';

ALTER TABLE smartorder.column_mappings ENABLE ROW LEVEL SECURITY;
ALTER TABLE smartorder.column_mappings FORCE ROW LEVEL SECURITY;
CREATE POLICY column_mappings_tenant_isolation ON smartorder.column_mappings
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

-- ---------------------------------------------------------------------------
-- Run lines — one per imported spreadsheet row
-- ---------------------------------------------------------------------------
CREATE TABLE smartorder.run_lines (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id                    BIGINT NOT NULL REFERENCES smartorder.runs(id) ON DELETE CASCADE,
    organization_id           BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    row_number                INT NOT NULL,

    raw                       JSONB NOT NULL DEFAULT '{}'::JSONB,
    raw_name                  TEXT,
    raw_sku                   TEXT,
    raw_barcode               TEXT,

    imported_qty              NUMERIC(12,2),
    qty_parse_note            TEXT,
    edited_qty                NUMERIC(12,2),
    effective_qty             NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (effective_qty >= 0),

    norm_name                 TEXT,
    identity_key              TEXT,

    matched_product_id        BIGINT REFERENCES catalog.products(id) ON DELETE SET NULL,
    match_method              TEXT NOT NULL DEFAULT 'none'
                              CHECK (match_method IN ('saving_product','learned_mapping','barcode','sku',
                                                      'exact_name','identity_key','fuzzy','alias','ai',
                                                      'manual','none')),
    match_confidence          NUMERIC(4,3) NOT NULL DEFAULT 0
                              CHECK (match_confidence >= 0 AND match_confidence <= 1),
    match_corrected_by_user   BOOLEAN NOT NULL DEFAULT false,

    outcome                   TEXT NOT NULL DEFAULT 'unmatched'
                              CHECK (outcome IN ('ordered','no_supplier','coverage_blocked',
                                                 'institutional_blocked','out_of_stock','below_min_qty',
                                                 'unmatched','zero_qty','removed')),
    outcome_reason            TEXT,
    consolidated_into_line_id BIGINT REFERENCES smartorder.run_lines(id) ON DELETE SET NULL,

    created_at                TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at                TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE  smartorder.run_lines IS 'صفوف الملف المستورد';
COMMENT ON COLUMN smartorder.run_lines.raw IS 'الخلايا كما وردت - تُحفظ حرفيًا حتى يظل الصف مفهومًا للمشتري';
COMMENT ON COLUMN smartorder.run_lines.qty_parse_note IS 'سبب تعذّر قراءة الكمية - لا تُحوّل الخلية صامتة إلى صفر';
COMMENT ON COLUMN smartorder.run_lines.effective_qty IS 'الكمية الفعلية = المعدلة، وإلا المستوردة، وإلا الافتراضية';
COMMENT ON COLUMN smartorder.run_lines.match_method IS 'طريقة المطابقة - تظهر للمشتري ليعرف ما يستحق المراجعة';
COMMENT ON COLUMN smartorder.run_lines.outcome IS 'نتيجة الصف - تميّز بين غير متطابق ولا يوجد مورد وممنوع بالتغطية';

CREATE UNIQUE INDEX run_lines_run_row_key ON smartorder.run_lines (run_id, row_number);
CREATE INDEX run_lines_run_outcome_idx ON smartorder.run_lines (run_id, outcome);
CREATE INDEX run_lines_run_product_idx ON smartorder.run_lines (run_id, matched_product_id);
CREATE INDEX run_lines_org_idx         ON smartorder.run_lines (organization_id);

CREATE TRIGGER run_lines_touch BEFORE UPDATE ON smartorder.run_lines
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

ALTER TABLE smartorder.run_lines ENABLE ROW LEVEL SECURITY;
ALTER TABLE smartorder.run_lines FORCE ROW LEVEL SECURITY;
CREATE POLICY run_lines_tenant_isolation ON smartorder.run_lines
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

-- ---------------------------------------------------------------------------
-- Line candidates — every vendor offer considered, including the rejected ones
-- ---------------------------------------------------------------------------
CREATE TABLE smartorder.line_candidates (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    line_id             BIGINT NOT NULL REFERENCES smartorder.run_lines(id) ON DELETE CASCADE,
    organization_id     BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    vendor_org_id       BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    variant_id          BIGINT NOT NULL REFERENCES catalog.product_variants(id) ON DELETE CASCADE,
    branch_id           BIGINT REFERENCES org.branches(id) ON DELETE SET NULL,

    price               NUMERIC(12,2) NOT NULL DEFAULT 0,
    discount            NUMERIC(12,2) NOT NULL DEFAULT 0,
    net_unit_price      NUMERIC(12,2) NOT NULL DEFAULT 0,
    unit                TEXT,
    min_order_qty       INT NOT NULL DEFAULT 1,
    stock_qty           INT NOT NULL DEFAULT 0,
    is_followed         BOOLEAN NOT NULL DEFAULT false,

    eligible            BOOLEAN NOT NULL DEFAULT false,
    ineligible_reason   TEXT CHECK (ineligible_reason IS NULL OR ineligible_reason IN
                            ('own_org','inactive','institutional','coverage','stock','min_qty')),
    coverage_distance_m INT,

    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- A buyer never buys from itself. Enforced in the retrieval query too; this
    -- is the backstop that makes the rule impossible to lose in a refactor.
    CONSTRAINT line_candidates_not_own_org CHECK (vendor_org_id <> organization_id)
);

COMMENT ON TABLE  smartorder.line_candidates IS 'عروض الموردين المرشحة لكل صف - تشمل المستبعدة وسبب استبعادها';
COMMENT ON COLUMN smartorder.line_candidates.organization_id IS 'مؤسسة المشتري - وليس المورد';
COMMENT ON COLUMN smartorder.line_candidates.net_unit_price IS 'السعر الصافي للوحدة بعد الخصم - أساس المقارنة';
COMMENT ON COLUMN smartorder.line_candidates.stock_qty IS 'المخزون من inventory.stocks وليس من نموذج القراءة';
COMMENT ON COLUMN smartorder.line_candidates.ineligible_reason IS 'أول سبب فشل بالترتيب - وهو الأكثر فائدة للمشتري';

CREATE INDEX line_candidates_line_eligible_idx ON smartorder.line_candidates (line_id, eligible);
CREATE INDEX line_candidates_line_price_idx    ON smartorder.line_candidates (line_id, net_unit_price);
CREATE INDEX line_candidates_org_idx           ON smartorder.line_candidates (organization_id);
CREATE INDEX line_candidates_vendor_idx        ON smartorder.line_candidates (vendor_org_id);

ALTER TABLE smartorder.line_candidates ENABLE ROW LEVEL SECURITY;
ALTER TABLE smartorder.line_candidates FORCE ROW LEVEL SECURITY;
CREATE POLICY line_candidates_tenant_isolation ON smartorder.line_candidates
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

-- ---------------------------------------------------------------------------
-- Line selections — the chosen candidate and why
-- ---------------------------------------------------------------------------
CREATE TABLE smartorder.line_selections (
    line_id              BIGINT PRIMARY KEY REFERENCES smartorder.run_lines(id) ON DELETE CASCADE,
    organization_id      BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    candidate_id         BIGINT NOT NULL REFERENCES smartorder.line_candidates(id) ON DELETE CASCADE,
    decided_by           TEXT NOT NULL
                         CHECK (decided_by IN ('lowest_price','highest_discount','followed_suppliers',
                                               'default','only_candidate','user')),
    tolerance_applied    BOOLEAN NOT NULL DEFAULT false,
    skipped_candidate_id BIGINT REFERENCES smartorder.line_candidates(id) ON DELETE SET NULL,
    skipped_excess_pct   NUMERIC(6,2),
    user_overridden      BOOLEAN NOT NULL DEFAULT false,
    line_net             NUMERIC(12,2) NOT NULL DEFAULT 0,
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE  smartorder.line_selections IS 'المورد المختار لكل صف والمعيار الذي رجّحه';
COMMENT ON COLUMN smartorder.line_selections.skipped_candidate_id IS 'المورد الذي فاز بالمعيار الأعلى ورُفض لتجاوزه نطاق التسامح';
COMMENT ON COLUMN smartorder.line_selections.skipped_excess_pct IS 'نسبة تجاوزه للنطاق - تُعرض للمشتري';

CREATE INDEX line_selections_org_idx       ON smartorder.line_selections (organization_id);
CREATE INDEX line_selections_candidate_idx ON smartorder.line_selections (candidate_id);

CREATE TRIGGER line_selections_touch BEFORE UPDATE ON smartorder.line_selections
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

ALTER TABLE smartorder.line_selections ENABLE ROW LEVEL SECURITY;
ALTER TABLE smartorder.line_selections FORCE ROW LEVEL SECURITY;
CREATE POLICY line_selections_tenant_isolation ON smartorder.line_selections
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

-- ---------------------------------------------------------------------------
-- Run events — append-only progress and audit
-- ---------------------------------------------------------------------------
CREATE TABLE smartorder.run_events (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id          BIGINT NOT NULL REFERENCES smartorder.runs(id) ON DELETE CASCADE,
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    stage           TEXT NOT NULL
                    CHECK (stage IN ('parse','normalize','resolve','candidates',
                                     'adjudicate','select','finalize')),
    processed       INT,
    total           INT,
    message         JSONB,
    level           TEXT NOT NULL DEFAULT 'info' CHECK (level IN ('info','warn','error')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE smartorder.run_events IS 'تقدم التنفيذ - مصدر شريط التقدم وسجل التدقيق';

CREATE INDEX run_events_run_idx ON smartorder.run_events (run_id, id);

ALTER TABLE smartorder.run_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE smartorder.run_events FORCE ROW LEVEL SECURITY;
CREATE POLICY run_events_tenant_isolation ON smartorder.run_events
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

-- ---------------------------------------------------------------------------
-- Criteria profiles — the buyer's remembered defaults
-- ---------------------------------------------------------------------------
CREATE TABLE smartorder.criteria_profiles (
    organization_id     BIGINT PRIMARY KEY REFERENCES org.organizations(id) ON DELETE CASCADE,
    criteria            JSONB NOT NULL DEFAULT '[]'::JSONB,
    tolerance_pct       NUMERIC(5,2) NOT NULL DEFAULT 5.00 CHECK (tolerance_pct >= 0 AND tolerance_pct <= 100),
    default_quantity    INT NOT NULL DEFAULT 0 CHECK (default_quantity >= 0),
    use_saving_products BOOLEAN NOT NULL DEFAULT false,
    use_ai_matching     BOOLEAN NOT NULL DEFAULT false,
    last_branch_id      BIGINT REFERENCES org.branches(id) ON DELETE SET NULL,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE smartorder.criteria_profiles IS 'إعدادات المشتري المحفوظة - تُقترح تلقائيًا في الطلب التالي';

CREATE TRIGGER criteria_profiles_touch BEFORE UPDATE ON smartorder.criteria_profiles
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

ALTER TABLE smartorder.criteria_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE smartorder.criteria_profiles FORCE ROW LEVEL SECURITY;
CREATE POLICY criteria_profiles_tenant_isolation ON smartorder.criteria_profiles
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

