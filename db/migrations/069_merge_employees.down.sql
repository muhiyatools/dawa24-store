-- 069_merge_employees (down)
--
-- Recreate hr.employees and move the folded rows back. Only members carrying a
-- non-empty employee_code (the 069-migrated set; pre-052 members hold '')
-- come back as employees.

BEGIN;

CREATE TABLE hr.employees (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id       UUID NOT NULL DEFAULT gen_random_uuid(),
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    user_id         BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    employee_code   TEXT NOT NULL,
    job_title       TEXT NOT NULL,
    base_salary     NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    variable_salary NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    status          TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','suspended','pending')),
    hired_at        DATE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT employees_code_unique UNIQUE (organization_id, employee_code)
);

CREATE UNIQUE INDEX employees_public_id_key ON hr.employees (public_id);
CREATE INDEX employees_org_idx  ON hr.employees (organization_id);
CREATE INDEX employees_user_idx ON hr.employees (user_id);

CREATE TRIGGER employees_touch BEFORE UPDATE ON hr.employees
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

ALTER TABLE hr.employees ENABLE ROW LEVEL SECURITY;
ALTER TABLE hr.employees FORCE ROW LEVEL SECURITY;

CREATE POLICY employees_tenant_isolation ON hr.employees
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

INSERT INTO hr.employees (public_id, organization_id, user_id, employee_code, job_title,
                          base_salary, variable_salary, status, hired_at, created_at, updated_at)
SELECT public_id, organization_id, user_id, employee_code, job_title,
       base_salary, variable_salary, status, hired_at, created_at, updated_at
FROM org.members
WHERE employee_code <> '';

DROP INDEX IF EXISTS members_employee_code_org_unique;

ALTER TABLE org.members
    DROP COLUMN IF EXISTS hired_at,
    DROP COLUMN IF EXISTS public_id;

COMMIT;
