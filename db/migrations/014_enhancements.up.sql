-- 014_enhancements
--
-- Enhanced feature parity: User address book, customer wishlists,
-- vendor organization reviews, and organization followers.

BEGIN;

-- ---------------------------------------------------------------------------
-- User Address Book
-- ---------------------------------------------------------------------------
CREATE TABLE identity.user_addresses (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id    UUID NOT NULL DEFAULT gen_random_uuid(),
    user_id      BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    title        TEXT NOT NULL DEFAULT 'Home',
    address_line TEXT NOT NULL,
    city_id      BIGINT REFERENCES platform_admin.cities(id) ON DELETE SET NULL,
    country_id   BIGINT REFERENCES platform_admin.countries(id) ON DELETE SET NULL,
    postal_code  TEXT,
    phone_number TEXT,
    is_default   BOOLEAN NOT NULL DEFAULT false,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX user_addresses_public_id_key ON identity.user_addresses (public_id);
CREATE INDEX user_addresses_user_idx ON identity.user_addresses (user_id);

CREATE TRIGGER user_addresses_touch BEFORE UPDATE ON identity.user_addresses
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

-- ---------------------------------------------------------------------------
-- Customer Wishlists
-- ---------------------------------------------------------------------------
CREATE TABLE commerce.wishlists (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id  UUID NOT NULL DEFAULT gen_random_uuid(),
    user_id    BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES catalog.products(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT wishlists_user_product_unique UNIQUE (user_id, product_id)
);

CREATE UNIQUE INDEX wishlists_public_id_key ON commerce.wishlists (public_id);
CREATE INDEX wishlists_user_idx ON commerce.wishlists (user_id);

-- ---------------------------------------------------------------------------
-- Organization Reviews & Ratings
-- ---------------------------------------------------------------------------
CREATE TABLE org.organization_reviews (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id       UUID NOT NULL DEFAULT gen_random_uuid(),
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    user_id         BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    rating          SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    review_text     TEXT,
    is_approved     BOOLEAN NOT NULL DEFAULT true,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT org_reviews_user_unique UNIQUE (organization_id, user_id)
);

CREATE INDEX org_reviews_org_idx ON org.organization_reviews (organization_id);

-- ---------------------------------------------------------------------------
-- Organization Followers
-- ---------------------------------------------------------------------------
CREATE TABLE org.organization_followers (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    user_id         BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT org_followers_unique UNIQUE (organization_id, user_id)
);

CREATE INDEX org_followers_org_idx ON org.organization_followers (organization_id);

COMMIT;
