-- 040_org_highlight_sections
--
-- Per-organization merchandising (legacy organization_highlight_sections and
-- organization_highlight_section_items). A supplier curates rows of products /
-- offers on its own storefront, independent of the platform-level
-- promo.highlight_sections.

BEGIN;

CREATE TABLE IF NOT EXISTS org.highlight_sections (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    title           JSONB NOT NULL DEFAULT '{"ar":"","en":""}'::JSONB,
    slug            VARCHAR(64) NOT NULL DEFAULT '',
    display_order   INT NOT NULL DEFAULT 0,
    is_active       BOOLEAN NOT NULL DEFAULT true,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS highlight_sections_org_idx ON org.highlight_sections (organization_id, display_order);

CREATE TABLE IF NOT EXISTS org.highlight_section_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_id    BIGINT NOT NULL REFERENCES org.highlight_sections(id) ON DELETE CASCADE,
    product_id    BIGINT REFERENCES catalog.products(id) ON DELETE SET NULL,
    offer_id      BIGINT REFERENCES promo.offers(id) ON DELETE SET NULL,
    display_order INT NOT NULL DEFAULT 0,
    CHECK (product_id IS NOT NULL OR offer_id IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS highlight_section_items_section_idx ON org.highlight_section_items (section_id, display_order);

COMMENT ON TABLE org.highlight_sections IS 'أقسام ترويجية خاصة بالمؤسسة — per-organization merchandising rows';

ALTER TABLE org.highlight_sections ENABLE ROW LEVEL SECURITY;
ALTER TABLE org.highlight_sections FORCE ROW LEVEL SECURITY;

CREATE POLICY highlight_sections_tenant_isolation ON org.highlight_sections
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

ALTER TABLE org.highlight_section_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE org.highlight_section_items FORCE ROW LEVEL SECURITY;

CREATE POLICY highlight_items_via_section ON org.highlight_section_items
    USING (EXISTS (
        SELECT 1 FROM org.highlight_sections s
        WHERE s.id = section_id AND platform.tenant_visible(s.organization_id)
    ))
    WITH CHECK (EXISTS (
        SELECT 1 FROM org.highlight_sections s
        WHERE s.id = section_id AND platform.tenant_visible(s.organization_id)
    ));

COMMIT;
