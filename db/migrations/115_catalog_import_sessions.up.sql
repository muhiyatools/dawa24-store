-- 115_catalog_import_sessions (up)
--
-- Staging for admin master-catalogue imports.
--
-- The import used to be a single request: upload, parse, write. For a
-- nine-thousand-row supplier catalogue that asks the admin to approve a change
-- they cannot see. These tables hold the parsed result between "analyse the
-- file" and "commit it", so every row, every match, and every value an
-- enrichment pass filled in can be reviewed before the catalogue is touched.
--
-- ingest.import_sessions is the vendor-side equivalent and is deliberately left
-- alone: it stages a vendor's price list and its reconciler writes variants and
-- stock against an existing master product. This one stages the master
-- catalogue itself. Same shape, different destination, different lifetime.

BEGIN;

CREATE TABLE IF NOT EXISTS catalog.import_sessions (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id         UUID NOT NULL DEFAULT gen_random_uuid(),
    organization_id   BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    created_by        BIGINT REFERENCES identity.users(id) ON DELETE SET NULL,

    filename          TEXT NOT NULL DEFAULT '',
    file_size_bytes   BIGINT NOT NULL DEFAULT 0,
    source_format     TEXT NOT NULL DEFAULT '',
    sheet_name        TEXT NOT NULL DEFAULT '',
    delimiter         TEXT NOT NULL DEFAULT '',

    status            TEXT NOT NULL DEFAULT 'draft'
                      CHECK (status IN ('draft','ready','committed','cancelled','failed')),
    import_mode       TEXT NOT NULL DEFAULT 'update_and_add'
                      CHECK (import_mode IN ('add_new_only','update_existing_only','clear_and_add','update_and_add')),

    -- The enrichment switches and the admin's column/row corrections. Both are
    -- documents rather than columns because they are read and written whole,
    -- only ever by this feature, and their shape follows the wizard's.
    options           JSONB NOT NULL DEFAULT '{}'::JSONB,
    layout_overrides  JSONB NOT NULL DEFAULT '{}'::JSONB,

    total_rows        INT NOT NULL DEFAULT 0,
    parsed_rows       INT NOT NULL DEFAULT 0,
    insert_rows       INT NOT NULL DEFAULT 0,
    update_rows       INT NOT NULL DEFAULT 0,
    skip_rows         INT NOT NULL DEFAULT 0,
    error_rows        INT NOT NULL DEFAULT 0,
    warning_rows      INT NOT NULL DEFAULT 0,
    block_count       INT NOT NULL DEFAULT 0,

    new_brands        JSONB NOT NULL DEFAULT '[]'::JSONB,

    ai_calls          INT NOT NULL DEFAULT 0,
    ai_applied        INT NOT NULL DEFAULT 0,
    ai_note           TEXT NOT NULL DEFAULT '',
    ai_fallback       BOOLEAN NOT NULL DEFAULT false,

    error_message     TEXT NOT NULL DEFAULT '',
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    committed_at      TIMESTAMPTZ,
    -- An abandoned review holds a copy of the admin's whole file. Without an
    -- expiry the staging tables grow without bound; the cleanup runs whenever a
    -- new session is opened, so no scheduled job is needed to collect them.
    expires_at        TIMESTAMPTZ NOT NULL DEFAULT now() + INTERVAL '24 hours'
);

CREATE UNIQUE INDEX IF NOT EXISTS catalog_import_sessions_public_id_key
    ON catalog.import_sessions (public_id);
CREATE INDEX IF NOT EXISTS catalog_import_sessions_org_created
    ON catalog.import_sessions (organization_id, created_at DESC);
CREATE INDEX IF NOT EXISTS catalog_import_sessions_expiry
    ON catalog.import_sessions (expires_at) WHERE status IN ('draft','ready');

CREATE TRIGGER catalog_import_sessions_touch BEFORE UPDATE ON catalog.import_sessions
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

CREATE TABLE IF NOT EXISTS catalog.import_staging_rows (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id         BIGINT NOT NULL REFERENCES catalog.import_sessions(id) ON DELETE CASCADE,
    -- The row number in the admin's own spreadsheet, one-based, so a finding
    -- here points at a row they can open and look at.
    source_row         INT NOT NULL DEFAULT 0,
    block_index        INT NOT NULL DEFAULT 0,

    action             TEXT NOT NULL DEFAULT 'insert'
                       CHECK (action IN ('insert','update','skip')),
    included           BOOLEAN NOT NULL DEFAULT true,

    matched_product_id BIGINT REFERENCES catalog.products(id) ON DELETE SET NULL,
    match_reason       TEXT NOT NULL DEFAULT '',

    payload            JSONB NOT NULL,
    issues             JSONB NOT NULL DEFAULT '[]'::JSONB,
    ai_changes         JSONB NOT NULL DEFAULT '[]'::JSONB,

    -- Denormalised for the review table's search box, which must not have to
    -- reach into the payload document on every keystroke over 9,000 rows.
    search_name        TEXT NOT NULL DEFAULT '',
    search_code        TEXT NOT NULL DEFAULT '',
    has_error          BOOLEAN NOT NULL DEFAULT false,
    has_warning        BOOLEAN NOT NULL DEFAULT false,
    has_ai             BOOLEAN NOT NULL DEFAULT false,

    created_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS catalog_import_rows_session
    ON catalog.import_staging_rows (session_id, source_row);
CREATE INDEX IF NOT EXISTS catalog_import_rows_action
    ON catalog.import_staging_rows (session_id, action) WHERE included;
CREATE INDEX IF NOT EXISTS catalog_import_rows_flags
    ON catalog.import_staging_rows (session_id, has_error, has_warning, has_ai);
CREATE INDEX IF NOT EXISTS catalog_import_rows_search
    ON catalog.import_staging_rows USING gin (search_name gin_trgm_ops);

COMMENT ON TABLE catalog.import_sessions IS
    'جلسات استيراد الكتالوج المعتمد — مرحلة المراجعة قبل الحفظ النهائي';
COMMENT ON TABLE catalog.import_staging_rows IS
    'صفوف الاستيراد المؤقتة بانتظار مراجعة المشرف وتأكيده';

COMMIT;
