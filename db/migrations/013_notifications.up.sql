-- 013_notifications
--
-- Notifications: Multi-channel delivery logs (SMS, WhatsApp, Email, In-App),
-- notification templates, and user notification feeds.

BEGIN;

CREATE SCHEMA IF NOT EXISTS notifications;

-- ---------------------------------------------------------------------------
-- Notification Templates
-- ---------------------------------------------------------------------------
CREATE TABLE notifications.templates (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id  UUID NOT NULL DEFAULT gen_random_uuid(),
    slug       TEXT NOT NULL UNIQUE,
    channel    TEXT NOT NULL CHECK (channel IN ('sms','whatsapp','email','in_app')),
    title      JSONB NOT NULL,
    body       JSONB NOT NULL,
    is_active  BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Notification Logs (Dispatched Messages)
-- ---------------------------------------------------------------------------
CREATE TABLE notifications.logs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id       UUID NOT NULL DEFAULT gen_random_uuid(),
    user_id         BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    organization_id BIGINT REFERENCES org.organizations(id) ON DELETE SET NULL,
    channel         TEXT NOT NULL CHECK (channel IN ('sms','whatsapp','email','in_app')),
    recipient       TEXT NOT NULL,
    title           TEXT NOT NULL,
    body            TEXT NOT NULL,
    status          TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','sent','delivered','failed')),
    error_message   TEXT,
    is_read         BOOLEAN NOT NULL DEFAULT false,
    read_at         TIMESTAMPTZ,
    sent_at         TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX notification_logs_public_id_key ON notifications.logs (public_id);
CREATE INDEX notification_logs_user_idx ON notifications.logs (user_id, created_at DESC);
CREATE INDEX notification_logs_unread_idx ON notifications.logs (user_id) WHERE is_read = false;

ALTER TABLE notifications.logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE notifications.logs FORCE ROW LEVEL SECURITY;

CREATE POLICY notification_logs_tenant_isolation ON notifications.logs
    USING (organization_id IS NULL OR platform.tenant_visible(organization_id))
    WITH CHECK (organization_id IS NULL OR platform.tenant_visible(organization_id));

COMMIT;
