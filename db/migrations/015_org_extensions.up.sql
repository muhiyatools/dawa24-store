-- 015_org_extensions
--
-- Organization extensions: Social media links, organizational policies,
-- and organization contact phone registries.

BEGIN;

-- ---------------------------------------------------------------------------
-- Organization Social Media Links
-- ---------------------------------------------------------------------------
CREATE TABLE org.organization_social_media (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id       UUID NOT NULL DEFAULT gen_random_uuid(),
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    platform        TEXT NOT NULL,
    url             TEXT NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX org_social_media_org_idx ON org.organization_social_media (organization_id);

ALTER TABLE org.organization_social_media ENABLE ROW LEVEL SECURITY;
ALTER TABLE org.organization_social_media FORCE ROW LEVEL SECURITY;

CREATE POLICY org_social_media_tenant_isolation ON org.organization_social_media
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

-- ---------------------------------------------------------------------------
-- Organization Policies (Terms, Return Policies, Delivery Terms)
-- ---------------------------------------------------------------------------
CREATE TABLE org.organization_policies (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id       UUID NOT NULL DEFAULT gen_random_uuid(),
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    title           TEXT NOT NULL,
    content         TEXT NOT NULL,
    policy_type     TEXT NOT NULL DEFAULT 'terms' CHECK (policy_type IN ('terms','returns','privacy','shipping')),
    is_active       BOOLEAN NOT NULL DEFAULT true,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX org_policies_org_idx ON org.organization_policies (organization_id);

ALTER TABLE org.organization_policies ENABLE ROW LEVEL SECURITY;
ALTER TABLE org.organization_policies FORCE ROW LEVEL SECURITY;

CREATE POLICY org_policies_tenant_isolation ON org.organization_policies
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

-- ---------------------------------------------------------------------------
-- User Organization Numbers (Official registered contact phones)
-- ---------------------------------------------------------------------------
CREATE TABLE org.user_organization_numbers (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    user_id         BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    phone_number    TEXT NOT NULL,
    is_verified     BOOLEAN NOT NULL DEFAULT false,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX user_org_numbers_org_idx ON org.user_organization_numbers (organization_id);

ALTER TABLE org.user_organization_numbers ENABLE ROW LEVEL SECURITY;
ALTER TABLE org.user_organization_numbers FORCE ROW LEVEL SECURITY;

CREATE POLICY user_org_numbers_tenant_isolation ON org.user_organization_numbers
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

COMMIT;
