-- Purchase Requests & Purchase Request Lines (Plan V5 Phase 3 Task 3.1):
-- Customer manual procurement workflow matching Laravel's multi-step purchase request wizard and history.

BEGIN;

CREATE TABLE commerce.purchase_requests (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id          UUID NOT NULL DEFAULT gen_random_uuid(),
    request_number     VARCHAR(64) NOT NULL UNIQUE,
    customer_id        BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    organization_id    BIGINT REFERENCES org.organizations(id) ON DELETE CASCADE,
    branch_id          BIGINT REFERENCES org.organization_branches(id) ON DELETE SET NULL,
    vendor_org_id      BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    vendor_branch_id   BIGINT REFERENCES org.organization_branches(id) ON DELETE SET NULL,
    status             VARCHAR(32) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'processing', 'completed', 'cancelled')),
    total_items        INTEGER NOT NULL DEFAULT 0,
    estimated_total    NUMERIC(12,2) NOT NULL DEFAULT 0,
    buyer_notes        TEXT,
    vendor_notes       TEXT,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    responded_at       TIMESTAMPTZ,
    responded_by       BIGINT REFERENCES identity.users(id) ON DELETE SET NULL
);

CREATE TABLE commerce.purchase_request_lines (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id         BIGINT NOT NULL REFERENCES commerce.purchase_requests(id) ON DELETE CASCADE,
    product_id         BIGINT REFERENCES catalog.products(id) ON DELETE SET NULL,
    product_name       TEXT NOT NULL,
    product_sku        TEXT,
    quantity           INTEGER NOT NULL CHECK (quantity > 0),
    target_price       NUMERIC(12,2),
    target_discount    NUMERIC(5,2),
    offered_price      NUMERIC(12,2),
    offered_discount   NUMERIC(5,2),
    status             VARCHAR(32) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected', 'modified')),
    notes              TEXT,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX purchase_requests_customer_idx ON commerce.purchase_requests (customer_id, status);
CREATE INDEX purchase_requests_org_idx ON commerce.purchase_requests (organization_id, status);
CREATE INDEX purchase_requests_vendor_idx ON commerce.purchase_requests (vendor_org_id, status);
CREATE INDEX purchase_request_lines_request_idx ON commerce.purchase_request_lines (request_id);
CREATE INDEX purchase_request_lines_product_idx ON commerce.purchase_request_lines (product_id);

ALTER TABLE commerce.purchase_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE commerce.purchase_requests FORCE ROW LEVEL SECURITY;

CREATE POLICY purchase_requests_tenant_isolation ON commerce.purchase_requests
    USING (platform.tenant_visible(organization_id) OR platform.tenant_visible(vendor_org_id))
    WITH CHECK (platform.tenant_visible(organization_id) OR platform.tenant_visible(vendor_org_id));

ALTER TABLE commerce.purchase_request_lines ENABLE ROW LEVEL SECURITY;
ALTER TABLE commerce.purchase_request_lines FORCE ROW LEVEL SECURITY;

CREATE POLICY purchase_request_lines_tenant_isolation ON commerce.purchase_request_lines
    USING (
        EXISTS (
            SELECT 1 FROM commerce.purchase_requests pr
            WHERE pr.id = purchase_request_lines.request_id
            AND (platform.tenant_visible(pr.organization_id) OR platform.tenant_visible(pr.vendor_org_id))
        )
    )
    WITH CHECK (
        EXISTS (
            SELECT 1 FROM commerce.purchase_requests pr
            WHERE pr.id = purchase_request_lines.request_id
            AND (platform.tenant_visible(pr.organization_id) OR platform.tenant_visible(pr.vendor_org_id))
        )
    );

COMMIT;
