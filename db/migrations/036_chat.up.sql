-- 036_chat
--
-- Buyer <-> supplier messaging (legacy chat_conversations / chat_messages).
-- A conversation is visible to both its organization and its counterparty, so
-- the RLS policy here is wider than the standard single-tenant helper: it
-- admits a row when EITHER side matches the current tenant. The WHERE clauses
-- in the repository mirror that predicate exactly.

BEGIN;

-- The schema itself. Every other schema is created in 001_foundation, and this
-- migration introduced a new one without adding it there or here, so the first
-- CREATE TABLE failed with "schema chat does not exist" and the migrate
-- container exited 1 on every boot. The server never started behind it, which
-- is what the 502 was.
CREATE SCHEMA IF NOT EXISTS chat;

COMMENT ON SCHEMA chat IS 'Buyer/supplier conversations and messages';

CREATE TABLE chat.conversations (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id           UUID NOT NULL DEFAULT gen_random_uuid(),
    organization_id     BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    counterparty_org_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    subject             JSONB NOT NULL DEFAULT '{"ar":"","en":""}'::JSONB,
    context_type        TEXT NOT NULL DEFAULT 'general'
                        CHECK (context_type IN ('order','quote','product','general')),
    context_id          BIGINT,
    status              TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','closed')),
    last_message_at     TIMESTAMPTZ,
    created_by_user_id  BIGINT REFERENCES identity.users(id) ON DELETE SET NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX conversations_public_id_key ON chat.conversations (public_id);
CREATE INDEX conversations_org_idx        ON chat.conversations (organization_id);
CREATE INDEX conversations_counterparty_idx ON chat.conversations (counterparty_org_id);

COMMENT ON TABLE  chat.conversations IS 'المحادثات — buyer<->supplier threads, visible to both organizations.';
COMMENT ON COLUMN chat.conversations.subject IS 'موضوع المحادثة // {"ar":"","en":""}';

CREATE TRIGGER conversations_touch BEFORE UPDATE ON chat.conversations
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

CREATE TABLE chat.messages (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES chat.conversations(id) ON DELETE CASCADE,
    sender_user_id  BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    sender_org_id   BIGINT REFERENCES org.organizations(id) ON DELETE SET NULL,
    body            TEXT NOT NULL DEFAULT '',
    attachments     JSONB NOT NULL DEFAULT '[]'::JSONB,
    read_at         TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX messages_conversation_idx ON chat.messages (conversation_id, created_at);

CREATE TABLE chat.participants (
    conversation_id BIGINT NOT NULL REFERENCES chat.conversations(id) ON DELETE CASCADE,
    user_id         BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    last_read_at    TIMESTAMPTZ,
    PRIMARY KEY (conversation_id, user_id)
);

CREATE INDEX participants_org_idx ON chat.participants (organization_id);

-- ---------------------------------------------------------------------------
-- Row-level security: a conversation is visible to BOTH sides.
-- ---------------------------------------------------------------------------
ALTER TABLE chat.conversations ENABLE ROW LEVEL SECURITY;
ALTER TABLE chat.conversations FORCE ROW LEVEL SECURITY;

CREATE POLICY conversations_both_sides ON chat.conversations
    USING (platform.tenant_visible(organization_id) OR platform.tenant_visible(counterparty_org_id))
    WITH CHECK (platform.tenant_visible(organization_id) OR platform.tenant_visible(counterparty_org_id));

ALTER TABLE chat.messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE chat.messages FORCE ROW LEVEL SECURITY;

-- A message is visible through its parent conversation. We re-derive the same
-- both-sides rule from the parent row rather than duplicating tenant columns.
CREATE POLICY messages_via_conversation ON chat.messages
    USING (EXISTS (
        SELECT 1 FROM chat.conversations c
        WHERE c.id = conversation_id
          AND (platform.tenant_visible(c.organization_id) OR platform.tenant_visible(c.counterparty_org_id))
    ));

ALTER TABLE chat.participants ENABLE ROW LEVEL SECURITY;
ALTER TABLE chat.participants FORCE ROW LEVEL SECURITY;

CREATE POLICY participants_tenant_isolation ON chat.participants
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

COMMIT;
