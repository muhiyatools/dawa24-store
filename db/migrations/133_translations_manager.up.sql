-- 133_translations_manager (up)
--
-- Adds the platform.translations table to allow dynamic runtime translations
-- management, search, and overrides across English and Arabic from the Admin Panel.

BEGIN;

CREATE TABLE IF NOT EXISTS platform.translations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key         TEXT NOT NULL UNIQUE,
    namespace   TEXT NOT NULL DEFAULT 'common',
    text_ar     TEXT NOT NULL DEFAULT '',
    text_en     TEXT NOT NULL DEFAULT '',
    description TEXT NOT NULL DEFAULT '',
    is_custom   BOOLEAN NOT NULL DEFAULT false,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_translations_namespace ON platform.translations (namespace);
CREATE INDEX IF NOT EXISTS idx_translations_key ON platform.translations (key);
CREATE INDEX IF NOT EXISTS idx_translations_custom ON platform.translations (is_custom);

COMMENT ON TABLE platform.translations IS 'جدول نصوص ومفاتيح الترجمة والتدويل للمنصة بكافة واجهاتها';

COMMIT;