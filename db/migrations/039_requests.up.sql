-- 039_requests
--
-- Document/action/approval requests between parties (legacy ask_fors). A
-- supplier asks a pharmacy for its licence; a pharmacy asks a supplier for a
-- certificate. Visible to both the requester's and the target's organization.

BEGIN;

CREATE TABLE IF NOT EXISTS workflow.requests (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id    UUID NOT NULL DEFAULT gen_random_uuid(),
    type         TEXT NOT NULL CHECK (type IN ('document','action','approval')),
    title        JSONB NOT NULL DEFAULT '{"ar":"","en":""}'::JSONB,
    description  TEXT NOT NULL DEFAULT '',
    status       TEXT NOT NULL DEFAULT 'pending'
                 CHECK (status IN ('pending','accepted','declined','cancelled')),
    action_url   TEXT NOT NULL DEFAULT '',
    from_user_id BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    from_org_id  BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    to_org_id    BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX requests_public_id_key ON workflow.requests (public_id);
CREATE INDEX requests_to_org_idx   ON workflow.requests (to_org_id, status);
CREATE INDEX requests_from_org_idx ON workflow.requests (from_org_id);

COMMENT ON TABLE workflow.requests IS 'طلبات المستندات والإجراءات — document/action requests between parties';

CREATE TRIGGER requests_touch BEFORE UPDATE ON workflow.requests
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

ALTER TABLE workflow.requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE workflow.requests FORCE ROW LEVEL SECURITY;

CREATE POLICY requests_both_sides ON workflow.requests
    USING (platform.tenant_visible(from_org_id) OR platform.tenant_visible(to_org_id))
    WITH CHECK (platform.tenant_visible(from_org_id) OR platform.tenant_visible(to_org_id));

COMMIT;
