-- 005_inventory
--
-- Inventory management: warehouses, stocks, movement ledger, and transfers.
--
-- Fixes legacy defect D4: UNIQUE(warehouse_id, product_variant_id) so that
-- sibling variants of a product can coexist within the same warehouse.

BEGIN;

-- ---------------------------------------------------------------------------
-- Warehouses (Tenant-owned)
-- ---------------------------------------------------------------------------
CREATE TABLE inventory.warehouses (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id       UUID NOT NULL DEFAULT gen_random_uuid(),
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    branch_id       BIGINT REFERENCES org.branches(id) ON DELETE SET NULL,
    name            TEXT NOT NULL,
    code            TEXT,
    address         TEXT,
    phone           TEXT,
    latitude        NUMERIC(10,8),
    longitude       NUMERIC(11,8),
    is_active       BOOLEAN NOT NULL DEFAULT true,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at      TIMESTAMPTZ
);

CREATE UNIQUE INDEX warehouses_public_id_key ON inventory.warehouses (public_id);
CREATE INDEX warehouses_org_idx    ON inventory.warehouses (organization_id) WHERE deleted_at IS NULL;
CREATE INDEX warehouses_branch_idx ON inventory.warehouses (branch_id);

CREATE TRIGGER warehouses_touch BEFORE UPDATE ON inventory.warehouses
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

ALTER TABLE inventory.warehouses ENABLE ROW LEVEL SECURITY;
ALTER TABLE inventory.warehouses FORCE ROW LEVEL SECURITY;

CREATE POLICY warehouses_tenant_isolation ON inventory.warehouses
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

-- ---------------------------------------------------------------------------
-- Stocks (Tenant-owned)
-- ---------------------------------------------------------------------------
CREATE TABLE inventory.stocks (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id    BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    warehouse_id       BIGINT NOT NULL REFERENCES inventory.warehouses(id) ON DELETE CASCADE,
    product_id         BIGINT NOT NULL REFERENCES catalog.products(id) ON DELETE CASCADE,
    product_variant_id BIGINT NOT NULL REFERENCES catalog.product_variants(id) ON DELETE CASCADE,
    quantity           INT NOT NULL DEFAULT 0,
    min_threshold      INT NOT NULL DEFAULT 1,
    negotiation        INT NOT NULL DEFAULT 0,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at         TIMESTAMPTZ,

    -- D4 FIX: Variants coexist within a warehouse
    CONSTRAINT stocks_warehouse_variant_unique UNIQUE (warehouse_id, product_variant_id),
    CONSTRAINT stocks_quantity_non_negative CHECK (quantity >= 0)
);

CREATE INDEX stocks_org_idx       ON inventory.stocks (organization_id) WHERE deleted_at IS NULL;
CREATE INDEX stocks_product_idx   ON inventory.stocks (product_id);
CREATE INDEX stocks_variant_idx   ON inventory.stocks (product_variant_id);
CREATE INDEX stocks_warehouse_idx ON inventory.stocks (warehouse_id);

CREATE TRIGGER stocks_touch BEFORE UPDATE ON inventory.stocks
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

ALTER TABLE inventory.stocks ENABLE ROW LEVEL SECURITY;
ALTER TABLE inventory.stocks FORCE ROW LEVEL SECURITY;

CREATE POLICY stocks_tenant_isolation ON inventory.stocks
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

-- ---------------------------------------------------------------------------
-- Stock Movement Ledger (Append-only)
-- ---------------------------------------------------------------------------
CREATE TABLE inventory.stock_movements (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    stock_id        BIGINT NOT NULL REFERENCES inventory.stocks(id) ON DELETE CASCADE,
    type            TEXT NOT NULL CHECK (type IN ('in','out','transfer','adjustment','order_reserve','order_release')),
    quantity_delta  INT NOT NULL,
    balance_after   INT NOT NULL,
    details         TEXT,
    reference_type  TEXT,
    reference_id    BIGINT,
    user_id         BIGINT REFERENCES identity.users(id) ON DELETE SET NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX stock_movements_stock_idx ON inventory.stock_movements (stock_id, created_at DESC);
CREATE INDEX stock_movements_org_idx   ON inventory.stock_movements (organization_id, created_at DESC);

ALTER TABLE inventory.stock_movements ENABLE ROW LEVEL SECURITY;
ALTER TABLE inventory.stock_movements FORCE ROW LEVEL SECURITY;

CREATE POLICY stock_movements_tenant_isolation ON inventory.stock_movements
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

-- ---------------------------------------------------------------------------
-- Warehouse Transfers
-- ---------------------------------------------------------------------------
CREATE TABLE inventory.warehouse_transfers (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id    BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    from_warehouse_id  BIGINT NOT NULL REFERENCES inventory.warehouses(id) ON DELETE CASCADE,
    to_warehouse_id    BIGINT NOT NULL REFERENCES inventory.warehouses(id) ON DELETE CASCADE,
    product_id         BIGINT NOT NULL REFERENCES catalog.products(id) ON DELETE CASCADE,
    product_variant_id BIGINT NOT NULL REFERENCES catalog.product_variants(id) ON DELETE CASCADE,
    quantity           INT NOT NULL CHECK (quantity > 0),
    status             TEXT NOT NULL DEFAULT 'pending'
                       CHECK (status IN ('pending','in_transit','completed','cancelled')),
    initiated_by       BIGINT REFERENCES identity.users(id) ON DELETE SET NULL,
    notes              TEXT,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT transfers_distinct_warehouses CHECK (from_warehouse_id <> to_warehouse_id)
);

CREATE INDEX transfers_org_idx  ON inventory.warehouse_transfers (organization_id);
CREATE INDEX transfers_from_idx ON inventory.warehouse_transfers (from_warehouse_id);
CREATE INDEX transfers_to_idx   ON inventory.warehouse_transfers (to_warehouse_id);

ALTER TABLE inventory.warehouse_transfers ENABLE ROW LEVEL SECURITY;
ALTER TABLE inventory.warehouse_transfers FORCE ROW LEVEL SECURITY;

CREATE POLICY warehouse_transfers_tenant_isolation ON inventory.warehouse_transfers
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

-- ---------------------------------------------------------------------------
-- Temporary Warehouses (Vendor Import Staging)
-- ---------------------------------------------------------------------------
CREATE TABLE inventory.temp_warehouses (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    name            TEXT NOT NULL,
    is_global       BOOLEAN NOT NULL DEFAULT false,
    created_by      BIGINT REFERENCES identity.users(id) ON DELETE SET NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at      TIMESTAMPTZ
);

ALTER TABLE inventory.temp_warehouses ENABLE ROW LEVEL SECURITY;
ALTER TABLE inventory.temp_warehouses FORCE ROW LEVEL SECURITY;

CREATE POLICY temp_warehouses_tenant_isolation ON inventory.temp_warehouses
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

COMMIT;
