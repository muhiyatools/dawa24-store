-- 071_merge_product_mappings (down)
--
-- Reverse the reshape. product_clients rows were folded without their user_id
-- (the V2 shape carries no user column), so that table comes back EMPTY; and
-- saving_products rows were not folded at all (no counterpart in the mapping
-- model), so it too comes back empty. In every other respect the migration is
-- exact: price/discount are converted back to custom_price/discount_bps.

BEGIN;

-- 1. Remove folded product_clients rows (customer_org_id IS NULL marks them).
DELETE FROM catalog.customer_product_mappings WHERE customer_org_id IS NULL;

-- 2. Convert canonical price/discount back to the 017-era columns.
ALTER TABLE catalog.customer_product_mappings
    ADD COLUMN IF NOT EXISTS custom_price NUMERIC(12,2),
    ADD COLUMN IF NOT EXISTS discount_bps INTEGER
        CHECK (discount_bps BETWEEN 0 AND 10000);

UPDATE catalog.customer_product_mappings
SET custom_price = price,
    discount_bps = ROUND(discount * 100.0)::integer
WHERE customer_org_id IS NOT NULL;

ALTER TABLE catalog.customer_product_mappings
    DROP COLUMN IF EXISTS raw_name,
    DROP COLUMN IF EXISTS branch_id,
    DROP COLUMN IF EXISTS price,
    DROP COLUMN IF EXISTS discount,
    DROP COLUMN IF EXISTS source,
    DROP COLUMN IF EXISTS status,
    ALTER COLUMN customer_org_id SET NOT NULL;

DROP INDEX IF EXISTS customer_product_mappings_raw_name_idx;

-- 3. Recreate the source tables (empty).
CREATE TABLE catalog.product_clients (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    user_id         BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    product_id      BIGINT REFERENCES catalog.products(id) ON DELETE CASCADE,
    name            TEXT NOT NULL,
    price           NUMERIC(12,2),
    discount        NUMERIC(5,2),
    type            TEXT NOT NULL DEFAULT 'sell' CHECK (type IN ('sell','buy')),
    status          TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','processed','rejected')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at      TIMESTAMPTZ
);

ALTER TABLE catalog.product_clients ENABLE ROW LEVEL SECURITY;
ALTER TABLE catalog.product_clients FORCE ROW LEVEL SECURITY;

CREATE POLICY product_clients_tenant_isolation ON catalog.product_clients
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

CREATE TABLE catalog.saving_products (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    product_id      BIGINT NOT NULL REFERENCES catalog.products(id) ON DELETE CASCADE,
    bundle_quantity INTEGER NOT NULL DEFAULT 1,
    bundle_discount NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    is_active       BOOLEAN NOT NULL DEFAULT true,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX saving_products_org_idx ON catalog.saving_products (organization_id);

ALTER TABLE catalog.saving_products ENABLE ROW LEVEL SECURITY;
ALTER TABLE catalog.saving_products FORCE ROW LEVEL SECURITY;

CREATE POLICY tenant_isolation ON catalog.saving_products
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

COMMIT;
