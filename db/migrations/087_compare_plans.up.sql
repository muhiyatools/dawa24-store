-- Compare-plan schema and entitlement tables (Plan V5 Phase 2 Task 2.1 / Parity Audit §8.2).

BEGIN;

CREATE SCHEMA IF NOT EXISTS compare;

-- ---------------------------------------------------------------------------
-- 1. Compare Plans
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS compare.plans (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id           UUID NOT NULL DEFAULT gen_random_uuid(),
    name                JSONB NOT NULL DEFAULT '{"ar": "", "en": ""}'::jsonb,
    slug                TEXT NOT NULL UNIQUE,
    description         JSONB NOT NULL DEFAULT '{"ar": "", "en": ""}'::jsonb,
    price_monthly       NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    price_yearly        NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    price_lifetime      NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    currency            TEXT NOT NULL DEFAULT 'EGP',
    trial_days          INTEGER NOT NULL DEFAULT 0,
    is_active           BOOLEAN NOT NULL DEFAULT true,
    is_public           BOOLEAN NOT NULL DEFAULT true,
    is_recommended      BOOLEAN NOT NULL DEFAULT false,
    sort_order          INTEGER NOT NULL DEFAULT 0,
    created_by          BIGINT REFERENCES identity.users(id) ON DELETE SET NULL,
    updated_by          BIGINT REFERENCES identity.users(id) ON DELETE SET NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at          TIMESTAMPTZ
);

COMMENT ON TABLE compare.plans IS 'خطط وباقات الاشتراك في محرك مقارنة الخصومات والأسعار الذكي';
COMMENT ON COLUMN compare.plans.slug IS 'المعرف النصي الفريد للباقة';
COMMENT ON COLUMN compare.plans.currency IS 'عملة الباقة (افتراضياً EGP - المنصة أحادية العملة Rule R1)';

CREATE UNIQUE INDEX IF NOT EXISTS compare_plans_public_id_idx ON compare.plans (public_id);
CREATE INDEX IF NOT EXISTS compare_plans_active_idx ON compare.plans (is_active, sort_order) WHERE deleted_at IS NULL;

-- ---------------------------------------------------------------------------
-- 2. Plan Features (Archive limits, session caps, AI flags)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS compare.plan_features (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id             BIGINT NOT NULL REFERENCES compare.plans(id) ON DELETE CASCADE,
    key                 TEXT NOT NULL,
    name                JSONB NOT NULL DEFAULT '{"ar": "", "en": ""}'::jsonb,
    description         JSONB NOT NULL DEFAULT '{"ar": "", "en": ""}'::jsonb,
    value               TEXT NOT NULL DEFAULT '',
    value_type          TEXT NOT NULL DEFAULT 'string'
                        CHECK (value_type IN ('boolean', 'integer', 'decimal', 'string', 'json')),
    is_active           BOOLEAN NOT NULL DEFAULT true,
    sort_order          INTEGER NOT NULL DEFAULT 0,
    created_by          BIGINT REFERENCES identity.users(id) ON DELETE SET NULL,
    updated_by          BIGINT REFERENCES identity.users(id) ON DELETE SET NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at          TIMESTAMPTZ,

    CONSTRAINT compare_plan_features_plan_key_unique UNIQUE (plan_id, key)
);

COMMENT ON TABLE compare.plan_features IS 'مزايا ومحددات خطط المقارنة (الحد الأقصى للملفات النشطة، عدد الجلسات، التوفيق بالذكاء الاصطناعي)';

CREATE INDEX IF NOT EXISTS compare_plan_features_plan_idx ON compare.plan_features (plan_id);

-- ---------------------------------------------------------------------------
-- 3. Plan Requests (Self-serve plan upgrade requests pending admin approval)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS compare.plan_requests (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id           UUID NOT NULL DEFAULT gen_random_uuid(),
    plan_id             BIGINT NOT NULL REFERENCES compare.plans(id) ON DELETE RESTRICT,
    organization_id     BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    user_id             BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    status              TEXT NOT NULL DEFAULT 'pending'
                        CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled')),
    notes               TEXT,
    rejection_reason    TEXT,
    reviewed_by         BIGINT REFERENCES identity.users(id) ON DELETE SET NULL,
    reviewed_at         TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at          TIMESTAMPTZ
);

COMMENT ON TABLE compare.plan_requests IS 'طلبات المؤسسات للاشتراك في باقات مقارنة الأسعار والخصومات';

CREATE INDEX IF NOT EXISTS compare_plan_requests_org_idx ON compare.plan_requests (organization_id);
CREATE INDEX IF NOT EXISTS compare_plan_requests_status_idx ON compare.plan_requests (status);

ALTER TABLE compare.plan_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE compare.plan_requests FORCE ROW LEVEL SECURITY;

DO $$ BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies 
        WHERE schemaname = 'compare' AND tablename = 'plan_requests' AND policyname = 'tenant_isolation_compare_plan_requests'
    ) THEN
        CREATE POLICY tenant_isolation_compare_plan_requests ON compare.plan_requests
            FOR ALL
            USING (platform.tenant_visible(organization_id))
            WITH CHECK (platform.tenant_visible(organization_id));
    END IF;
END $$;

-- ---------------------------------------------------------------------------
-- 4. Subscriptions
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS compare.subscriptions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id           UUID NOT NULL DEFAULT gen_random_uuid(),
    plan_id             BIGINT NOT NULL REFERENCES compare.plans(id) ON DELETE RESTRICT,
    organization_id     BIGINT REFERENCES org.organizations(id) ON DELETE CASCADE,
    user_id             BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    billing_period      TEXT NOT NULL DEFAULT 'monthly'
                        CHECK (billing_period IN ('monthly', 'yearly', 'lifetime', 'trial')),
    payment_method      TEXT DEFAULT 'cash',
    starts_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    ends_at             TIMESTAMPTZ,
    status              TEXT NOT NULL DEFAULT 'active'
                        CHECK (status IN ('pending', 'active', 'expired', 'cancelled', 'suspended')),
    seats               INTEGER NOT NULL DEFAULT 1 CHECK (seats > 0),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at          TIMESTAMPTZ
);

COMMENT ON TABLE compare.subscriptions IS 'اشتراكات المؤسسات والمستخدمين في باقات محرك مقارنة الخصومات';

CREATE INDEX IF NOT EXISTS compare_subscriptions_org_idx ON compare.subscriptions (organization_id);
CREATE INDEX IF NOT EXISTS compare_subscriptions_user_idx ON compare.subscriptions (user_id);
CREATE INDEX IF NOT EXISTS compare_subscriptions_status_idx ON compare.subscriptions (status, ends_at);

ALTER TABLE compare.subscriptions ENABLE ROW LEVEL SECURITY;
ALTER TABLE compare.subscriptions FORCE ROW LEVEL SECURITY;

DO $$ BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies 
        WHERE schemaname = 'compare' AND tablename = 'subscriptions' AND policyname = 'tenant_isolation_compare_subscriptions'
    ) THEN
        CREATE POLICY tenant_isolation_compare_subscriptions ON compare.subscriptions
            FOR ALL
            USING (organization_id IS NULL OR platform.tenant_visible(organization_id))
            WITH CHECK (organization_id IS NULL OR platform.tenant_visible(organization_id));
    END IF;
END $$;

-- ---------------------------------------------------------------------------
-- 5. Subscription User Seats
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS compare.subscription_users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id     BIGINT NOT NULL REFERENCES compare.subscriptions(id) ON DELETE CASCADE,
    user_id             BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    is_active           BOOLEAN NOT NULL DEFAULT true,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at          TIMESTAMPTZ,

    CONSTRAINT compare_sub_users_unique UNIQUE (subscription_id, user_id)
);

COMMENT ON TABLE compare.subscription_users IS 'المقاعد والمستخدمون المعينون للاستفادة من اشتراك باقة المقارنة';

CREATE INDEX IF NOT EXISTS compare_sub_users_user_idx ON compare.subscription_users (user_id);

-- ---------------------------------------------------------------------------
-- 6. User Sessions & Device Caps
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS compare.user_sessions (
    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id                       UUID NOT NULL DEFAULT gen_random_uuid(),
    subscription_user_id            BIGINT REFERENCES compare.subscription_users(id) ON DELETE CASCADE,
    user_id                         BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    session_id                      TEXT NOT NULL,
    device_uuid                     TEXT,
    is_active                       BOOLEAN NOT NULL DEFAULT true,
    device_name                     TEXT,
    device_type                     TEXT,
    platform                        TEXT,
    platform_version                TEXT,
    browser                         TEXT,
    browser_version                 TEXT,
    ip_address                      INET,
    user_agent                      TEXT,
    country                         TEXT DEFAULT 'Unknown',
    city                            TEXT DEFAULT 'Unknown',
    logged_in_at                    TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_activity_at                TIMESTAMPTZ NOT NULL DEFAULT now(),
    logged_out_at                   TIMESTAMPTZ,
    created_at                      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at                      TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at                      TIMESTAMPTZ
);

COMMENT ON TABLE compare.user_sessions IS 'جلسات وأجهزة الدخول المفتوحة لمحرك المقارنة لتطبيق سقف الجلسات المتزامنة';

CREATE INDEX IF NOT EXISTS compare_user_sessions_user_active_idx ON compare.user_sessions (user_id, is_active, last_activity_at);
CREATE INDEX IF NOT EXISTS compare_user_sessions_sub_user_idx ON compare.user_sessions (subscription_user_id);

