-- 019_promo_tracking
--
-- Promotional View/Click Tracking & Marketplace Highlight Sections

BEGIN;

CREATE TABLE promo.offer_views (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offer_id        BIGINT NOT NULL REFERENCES promo.offers(id) ON DELETE CASCADE,
    user_id         BIGINT REFERENCES identity.users(id) ON DELETE SET NULL,
    organization_id BIGINT REFERENCES org.organizations(id) ON DELETE SET NULL,
    ip_address      TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX offer_views_offer_idx ON promo.offer_views (offer_id, created_at DESC);

CREATE TABLE promo.offer_clicks (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offer_id        BIGINT NOT NULL REFERENCES promo.offers(id) ON DELETE CASCADE,
    user_id         BIGINT REFERENCES identity.users(id) ON DELETE SET NULL,
    organization_id BIGINT REFERENCES org.organizations(id) ON DELETE SET NULL,
    ip_address      TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX offer_clicks_offer_idx ON promo.offer_clicks (offer_id, created_at DESC);

CREATE TABLE promo.highlight_sections (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id     UUID NOT NULL DEFAULT gen_random_uuid(),
    title         JSONB NOT NULL,
    slug          TEXT NOT NULL UNIQUE,
    display_order INTEGER NOT NULL DEFAULT 0,
    is_active     BOOLEAN NOT NULL DEFAULT true,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE promo.highlight_section_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_id    BIGINT NOT NULL REFERENCES promo.highlight_sections(id) ON DELETE CASCADE,
    product_id    BIGINT REFERENCES catalog.products(id) ON DELETE CASCADE,
    offer_id      BIGINT REFERENCES promo.offers(id) ON DELETE CASCADE,
    display_order INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX highlight_section_items_section_idx ON promo.highlight_section_items (section_id, display_order);

COMMIT;
