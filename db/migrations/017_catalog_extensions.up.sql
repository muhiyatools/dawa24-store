-- 017_catalog_extensions
--
-- Catalog extensions: Customer-specific custom pricing, product stock/price alerts,
-- and bulk saving product collections.

BEGIN;

-- ---------------------------------------------------------------------------
-- Customer Product Mappings (Per-Customer/Pharmacy Special B2B Pricing)
-- ---------------------------------------------------------------------------
CREATE TABLE catalog.customer_product_mappings (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id    BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    customer_org_id    BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    product_id         BIGINT NOT NULL REFERENCES catalog.products(id) ON DELETE CASCADE,
    product_variant_id BIGINT REFERENCES catalog.product_variants(id) ON DELETE CASCADE,
    custom_price       NUMERIC(12,2),
    discount_bps       INTEGER CHECK (discount_bps BETWEEN 0 AND 10000),
    is_active          BOOLEAN NOT NULL DEFAULT true,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT customer_product_mapping_unique UNIQUE (organization_id, customer_org_id, product_id, product_variant_id)
);

CREATE INDEX customer_product_mappings_lookup_idx ON catalog.customer_product_mappings (customer_org_id, product_id);

ALTER TABLE catalog.customer_product_mappings ENABLE ROW LEVEL SECURITY;
ALTER TABLE catalog.customer_product_mappings FORCE ROW LEVEL SECURITY;

CREATE POLICY customer_product_mappings_tenant_isolation ON catalog.customer_product_mappings
    USING (platform.tenant_visible(organization_id) OR platform.tenant_visible(customer_org_id))
    WITH CHECK (platform.tenant_visible(organization_id));

-- ---------------------------------------------------------------------------
-- Product Alerts (Price Drop & Back-In-Stock Alerts)
-- ---------------------------------------------------------------------------
CREATE TABLE catalog.product_alerts (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id          UUID NOT NULL DEFAULT gen_random_uuid(),
    user_id            BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    product_id         BIGINT NOT NULL REFERENCES catalog.products(id) ON DELETE CASCADE,
    alert_type         TEXT NOT NULL CHECK (alert_type IN ('price_drop','in_stock','discount')),
    target_price       NUMERIC(12,2),
    is_triggered       BOOLEAN NOT NULL DEFAULT false,
    triggered_at       TIMESTAMPTZ,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX product_alerts_user_idx ON catalog.product_alerts (user_id);
CREATE INDEX product_alerts_product_idx ON catalog.product_alerts (product_id) WHERE is_triggered = false;

-- ---------------------------------------------------------------------------
-- Saving Products (Special promotional bundled deal collections)
-- ---------------------------------------------------------------------------
CREATE TABLE catalog.saving_products (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    product_id      BIGINT NOT NULL REFERENCES catalog.products(id) ON DELETE CASCADE,
    bundle_quantity INTEGER NOT NULL DEFAULT 1,
    bundle_discount NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    is_active       BOOLEAN NOT NULL DEFAULT true,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX saving_products_org_idx ON catalog.saving_products (organization_id);

COMMIT;
