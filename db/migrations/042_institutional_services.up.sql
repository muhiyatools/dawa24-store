-- 042_institutional_services
--
-- Hierarchical catalogue of institutional services (legacy institutional_works).
-- Public listing, detail, and a request flow that reuses workflow.requests.

BEGIN;

CREATE TABLE IF NOT EXISTS workflow.services (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id    UUID NOT NULL DEFAULT gen_random_uuid(),
    title        JSONB NOT NULL DEFAULT '{"ar":"","en":""}'::JSONB,
    description  JSONB NOT NULL DEFAULT '{"ar":"","en":""}'::JSONB,
    icon         TEXT NOT NULL DEFAULT '',
    pricing_type TEXT NOT NULL DEFAULT 'free'
                 CHECK (pricing_type IN ('free','paid','subscription')),
    parent_id    BIGINT REFERENCES workflow.services(id) ON DELETE SET NULL,
    is_active    BOOLEAN NOT NULL DEFAULT true,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS services_public_id_key ON workflow.services (public_id);
CREATE INDEX IF NOT EXISTS services_parent_idx ON workflow.services (parent_id) WHERE is_active;

COMMENT ON TABLE workflow.services IS 'الخدمات المؤسسية — hierarchical institutional service catalogue';

CREATE TRIGGER services_touch BEFORE UPDATE ON workflow.services
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

COMMIT;
