-- 148_ai_usage_ledger
--
-- A local record of every AI request the Store makes.
--
-- Until now nothing was written down. The usage cards and the AI logs screen
-- asked the Gateway live on every page render — one to three HTTP calls to
-- api.muhiya.com to draw a dashboard — and showed whatever came back, capped at
-- a hundred rows, with no history beyond the Gateway's own retention and
-- nothing at all when the Gateway was unreachable. What the screens could not
-- get, the handlers invented: a budget ceiling from the plan slug, a reset date
-- computed locally, a per-token cost from rates that appear in no price list.
--
-- Every field below already exists on gateway.Response at the moment a call
-- returns and was simply discarded. Recording it makes the tenant's own history
-- ours: queryable, filterable, attributable to the feature that spent it, and
-- still there when the Gateway is not.
--
-- The Gateway remains the authority on the live budget window. This is the
-- ledger, not the meter.

BEGIN;

CREATE SCHEMA IF NOT EXISTS ai;

COMMENT ON SCHEMA ai IS 'استهلاك الذكاء الاصطناعي - سجل الطلبات والتكلفة لكل منشأة';

CREATE TABLE IF NOT EXISTS ai.usage_events (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id   BIGINT       NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    user_id           BIGINT       NOT NULL DEFAULT 0,

    -- capability is the business task asked for (product.match, catalog.chat),
    -- never a provider or a model. It is the vocabulary the Store speaks.
    capability        TEXT         NOT NULL DEFAULT '',
    -- feature is the screen or tool that asked, which is what a pharmacy
    -- actually recognises on the usage log: "الطلب الذكي", "استيراد الأصناف".
    feature           TEXT         NOT NULL DEFAULT '',

    -- model is whatever the Gateway resolved the request to. Empty when it
    -- named none: an unnamed model is recorded as unnamed, not guessed.
    model             TEXT         NOT NULL DEFAULT '',
    -- gateway_request_id ties a row back to the Gateway's own request_logs, so
    -- a disputed charge can be traced across both systems.
    gateway_request_id TEXT        NOT NULL DEFAULT '',

    input_tokens      INTEGER      NOT NULL DEFAULT 0,
    output_tokens     INTEGER      NOT NULL DEFAULT 0,

    -- Cost is stored in nano-USD as an integer, never as a float. A fraction of
    -- a cent per request over a million requests is a real number of pounds,
    -- and binary floating point loses it.
    cost_nano_usd     BIGINT       NOT NULL DEFAULT 0,
    -- cost_known separates "this request was free" from "the Gateway did not
    -- publish a price". Summing an unknown as zero understates a tenant's bill.
    cost_known        BOOLEAN      NOT NULL DEFAULT FALSE,

    duration_ms       INTEGER      NOT NULL DEFAULT 0,

    -- status is the Store's own verdict: success, failed, disabled, timeout.
    status            TEXT         NOT NULL DEFAULT 'success',
    -- finish_reason is the upstream's word for why generation stopped. "length"
    -- means the answer was cut off, which is a silent correctness failure the
    -- caller must be able to see after the fact.
    finish_reason     TEXT         NOT NULL DEFAULT '',
    error_message     TEXT         NOT NULL DEFAULT '',

    -- from_cache marks a request the Gateway answered without billing.
    from_cache        BOOLEAN      NOT NULL DEFAULT FALSE,
    -- fallback marks a call that never reached a model, so the deterministic
    -- path answered. Counting those as AI usage would overstate what the
    -- feature actually costs and hide how often AI was unavailable.
    fallback          BOOLEAN      NOT NULL DEFAULT FALSE,

    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now()
);

COMMENT ON TABLE  ai.usage_events IS 'سجل كل استدعاء للذكاء الاصطناعي - منسوب للمنشأة التي دفعت ثمنه';
COMMENT ON COLUMN ai.usage_events.capability IS 'القدرة المطلوبة - ليست اسم مزود ولا نموذج';
COMMENT ON COLUMN ai.usage_events.feature IS 'الشاشة أو الأداة التي طلبت العملية';
COMMENT ON COLUMN ai.usage_events.cost_nano_usd IS 'التكلفة بالنانو دولار - عدد صحيح وليس عشرياً';
COMMENT ON COLUMN ai.usage_events.cost_known IS 'هل نشرت البوابة تكلفة فعلية لهذا الطلب';
COMMENT ON COLUMN ai.usage_events.fallback IS 'استُخدم المسار الحتمي - لم يصل الطلب إلى نموذج';

-- The listing query is always "this organisation, newest first", so the index
-- carries both columns in that order. A separate created_at index would still
-- make every tenant's page scan every other tenant's rows.
CREATE INDEX IF NOT EXISTS ai_usage_org_time_idx
    ON ai.usage_events (organization_id, created_at DESC);

-- The usage cards group by feature over a window, which this answers without
-- reading the whole tenant's history.
CREATE INDEX IF NOT EXISTS ai_usage_org_feature_time_idx
    ON ai.usage_events (organization_id, feature, created_at DESC);

ALTER TABLE ai.usage_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE ai.usage_events FORCE ROW LEVEL SECURITY;
CREATE POLICY ai_usage_tenant_isolation ON ai.usage_events
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

COMMIT;
