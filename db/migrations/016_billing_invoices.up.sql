-- 016_billing_invoices
--
-- B2B Invoicing: Official tax invoices, invoice line items, and customer payment methods.

BEGIN;

-- ---------------------------------------------------------------------------
-- Invoices
-- ---------------------------------------------------------------------------
CREATE TABLE billing.invoices (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id       UUID NOT NULL DEFAULT gen_random_uuid(),
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    customer_org_id BIGINT REFERENCES org.organizations(id) ON DELETE SET NULL,
    order_id        BIGINT REFERENCES commerce.orders(id) ON DELETE SET NULL,
    invoice_number  TEXT NOT NULL UNIQUE,
    issue_date      DATE NOT NULL DEFAULT CURRENT_DATE,
    due_date        DATE NOT NULL,
    subtotal        NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    tax_amount      NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    discount_amount NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    total_amount    NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    status          TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','issued','paid','overdue','cancelled')),
    payment_method  TEXT NOT NULL DEFAULT 'credit',
    notes           TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX invoices_org_idx ON billing.invoices (organization_id, issue_date DESC);
CREATE INDEX invoices_customer_idx ON billing.invoices (customer_org_id);

ALTER TABLE billing.invoices ENABLE ROW LEVEL SECURITY;
ALTER TABLE billing.invoices FORCE ROW LEVEL SECURITY;

CREATE POLICY invoices_tenant_isolation ON billing.invoices
    USING (platform.tenant_visible(organization_id) OR (customer_org_id IS NOT NULL AND platform.tenant_visible(customer_org_id)))
    WITH CHECK (platform.tenant_visible(organization_id));

-- ---------------------------------------------------------------------------
-- Invoice Line Items
-- ---------------------------------------------------------------------------
CREATE TABLE billing.invoice_lines (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id  BIGINT NOT NULL REFERENCES billing.invoices(id) ON DELETE CASCADE,
    product_id  BIGINT REFERENCES catalog.products(id) ON DELETE SET NULL,
    description TEXT NOT NULL,
    quantity    INTEGER NOT NULL CHECK (quantity > 0),
    unit_price  NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0.00),
    total_price NUMERIC(12,2) NOT NULL CHECK (total_price >= 0.00)
);

CREATE INDEX invoice_lines_invoice_idx ON billing.invoice_lines (invoice_id);

-- ---------------------------------------------------------------------------
-- User Payment Methods
-- ---------------------------------------------------------------------------
CREATE TABLE billing.user_payment_methods (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id          UUID NOT NULL DEFAULT gen_random_uuid(),
    user_id            BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    provider           TEXT NOT NULL,
    account_identifier TEXT NOT NULL,
    is_default         BOOLEAN NOT NULL DEFAULT false,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX user_payment_methods_user_idx ON billing.user_payment_methods (user_id);

COMMIT;
