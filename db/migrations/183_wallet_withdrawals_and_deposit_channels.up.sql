BEGIN;

-- 1. Create billing.wallet_withdrawals table
CREATE TABLE IF NOT EXISTS billing.wallet_withdrawals (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id               UUID NOT NULL DEFAULT gen_random_uuid(),
    wallet_id               BIGINT NOT NULL REFERENCES billing.wallets(id) ON DELETE CASCADE,
    user_id                 BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    organization_id         BIGINT REFERENCES org.organizations(id) ON DELETE SET NULL,
    amount                  NUMERIC(12,2) NOT NULL,
    currency                TEXT NOT NULL DEFAULT 'EGP',
    payout_method_type      TEXT NOT NULL DEFAULT '', -- 'bank', 'instapay', 'wallet', 'card'
    destination_details     TEXT NOT NULL DEFAULT '',
    user_payment_method_id  BIGINT REFERENCES billing.user_payment_methods(id) ON DELETE SET NULL,
    user_notes              TEXT,
    status                  TEXT NOT NULL DEFAULT 'pending'
                            CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled')),
    rejection_reason        TEXT,
    reviewed_by             BIGINT REFERENCES identity.users(id) ON DELETE SET NULL,
    reviewed_at             TIMESTAMPTZ,
    transaction_id          BIGINT REFERENCES billing.wallet_transactions(id) ON DELETE SET NULL,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_wallet_withdrawals_user ON billing.wallet_withdrawals (user_id, status);
CREATE INDEX IF NOT EXISTS idx_wallet_withdrawals_wallet ON billing.wallet_withdrawals (wallet_id, status);
CREATE INDEX IF NOT EXISTS idx_wallet_withdrawals_org ON billing.wallet_withdrawals (organization_id);

-- 2. Add channel & sender columns to billing.wallet_deposits
ALTER TABLE billing.wallet_deposits
    ADD COLUMN IF NOT EXISTS platform_method_id VARCHAR(64) REFERENCES billing.platform_payment_methods(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS sender_account TEXT NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS sender_payment_method_id BIGINT REFERENCES billing.user_payment_methods(id) ON DELETE SET NULL;

COMMIT;
