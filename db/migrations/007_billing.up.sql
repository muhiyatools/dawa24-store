-- 007_billing
--
-- Billing, wallets, double-entry wallet transactions ledger, payment integrations,
-- unified subscription plans, and feature entitlements.

BEGIN;

CREATE SCHEMA IF NOT EXISTS billing;

-- ---------------------------------------------------------------------------
-- Wallets & Append-Only Transaction Ledger
-- ---------------------------------------------------------------------------
CREATE TABLE billing.wallets (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id       UUID NOT NULL DEFAULT gen_random_uuid(),
    user_id         BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    organization_id BIGINT REFERENCES org.organizations(id) ON DELETE SET NULL,
    currency        TEXT NOT NULL DEFAULT 'EGP',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT wallets_user_currency_unique UNIQUE (user_id, currency)
);

CREATE UNIQUE INDEX wallets_public_id_key ON billing.wallets (public_id);
CREATE INDEX wallets_user_idx ON billing.wallets (user_id);
CREATE INDEX wallets_org_idx  ON billing.wallets (organization_id) WHERE organization_id IS NOT NULL;

CREATE TRIGGER wallets_touch BEFORE UPDATE ON billing.wallets
    FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

CREATE TABLE billing.wallet_transactions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id      BIGINT NOT NULL REFERENCES billing.wallets(id) ON DELETE CASCADE,
    type           TEXT NOT NULL
                   CHECK (type IN ('deposit','withdrawal','purchase','refund','bonus','penalty','transfer_in','transfer_out','adjustment')),
    amount         NUMERIC(12,2) NOT NULL, -- Positive for credit, negative for debit
    balance_after  NUMERIC(12,2) NOT NULL,
    reference_type TEXT,
    reference_id   BIGINT,
    description    TEXT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX wallet_tx_wallet_idx ON billing.wallet_transactions (wallet_id, created_at DESC);

-- ---------------------------------------------------------------------------
-- Payment Integrations & Payments
-- ---------------------------------------------------------------------------
CREATE TABLE billing.payment_integrations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id   UUID NOT NULL DEFAULT gen_random_uuid(),
    slug        TEXT NOT NULL UNIQUE,
    name        TEXT NOT NULL,
    provider    TEXT NOT NULL,
    config      JSONB NOT NULL DEFAULT '{}'::JSONB,
    is_active   BOOLEAN NOT NULL DEFAULT true,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE billing.payments (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id              UUID NOT NULL DEFAULT gen_random_uuid(),
    payment_integration_id BIGINT REFERENCES billing.payment_integrations(id) ON DELETE SET NULL,
    order_id               BIGINT REFERENCES commerce.orders(id) ON DELETE SET NULL,
    user_id                BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE RESTRICT,
    organization_id        BIGINT REFERENCES org.organizations(id) ON DELETE SET NULL,
    amount                 NUMERIC(12,2) NOT NULL,
    method                 TEXT NOT NULL,
    status                 TEXT NOT NULL DEFAULT 'pending'
                           CHECK (status IN ('pending','authorized','paid','failed','refunded')),
    transaction_id         TEXT,
    reference_number       TEXT,
    notes                  TEXT,
    paid_at                TIMESTAMPTZ,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX payments_public_id_key ON billing.payments (public_id);
CREATE INDEX payments_order_idx ON billing.payments (order_id);
CREATE INDEX payments_user_idx  ON billing.payments (user_id);

-- ---------------------------------------------------------------------------
-- Unified Subscription Plans & Entitlements (Resolving D7)
-- ---------------------------------------------------------------------------
CREATE TABLE billing.plans (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id     UUID NOT NULL DEFAULT gen_random_uuid(),
    slug          TEXT NOT NULL UNIQUE,
    name          JSONB NOT NULL,
    description   JSONB,
    price_month   NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    price_year    NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    duration_days INT NOT NULL DEFAULT 30,
    max_users     INT,
    is_active     BOOLEAN NOT NULL DEFAULT true,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE billing.plan_features (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id     BIGINT NOT NULL REFERENCES billing.plans(id) ON DELETE CASCADE,
    feature_key TEXT NOT NULL,
    value       TEXT NOT NULL DEFAULT 'true',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT plan_features_unique UNIQUE (plan_id, feature_key)
);

CREATE TABLE billing.subscriptions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id       UUID NOT NULL DEFAULT gen_random_uuid(),
    user_id         BIGINT NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    organization_id BIGINT REFERENCES org.organizations(id) ON DELETE SET NULL,
    plan_id         BIGINT NOT NULL REFERENCES billing.plans(id) ON DELETE RESTRICT,
    status          TEXT NOT NULL DEFAULT 'active'
                    CHECK (status IN ('active','trialing','past_due','cancelled','expired')),
    starts_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at      TIMESTAMPTZ NOT NULL,
    source_system   TEXT NOT NULL DEFAULT 'dawa24_v2', -- Provenance for legacy D7 collapse
    source_id       BIGINT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX subscriptions_public_id_key ON billing.subscriptions (public_id);
CREATE INDEX subscriptions_user_idx ON billing.subscriptions (user_id);
CREATE INDEX subscriptions_org_idx  ON billing.subscriptions (organization_id) WHERE organization_id IS NOT NULL;

COMMIT;
