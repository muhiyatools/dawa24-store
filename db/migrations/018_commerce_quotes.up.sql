-- 018_commerce_quotes
--
-- Quote Requests (was ask_fors / request_offers): Buyer-initiated bulk price quote inquiries.

BEGIN;

CREATE TABLE commerce.quote_requests (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id          UUID NOT NULL DEFAULT gen_random_uuid(),
    organization_id    BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    customer_org_id    BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    product_id         BIGINT REFERENCES catalog.products(id) ON DELETE SET NULL,
    product_name       TEXT NOT NULL,
    requested_quantity INTEGER NOT NULL CHECK (requested_quantity > 0),
    target_unit_price  NUMERIC(12,2),
    quote_unit_price   NUMERIC(12,2),
    status             TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','quoted','accepted','rejected','expired')),
    buyer_notes        TEXT,
    supplier_notes     TEXT,
    valid_until        TIMESTAMPTZ,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX quote_requests_org_idx ON commerce.quote_requests (organization_id, status);
CREATE INDEX quote_requests_customer_idx ON commerce.quote_requests (customer_org_id, status);

ALTER TABLE commerce.quote_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE commerce.quote_requests FORCE ROW LEVEL SECURITY;

CREATE POLICY quote_requests_tenant_isolation ON commerce.quote_requests
    USING (platform.tenant_visible(organization_id) OR platform.tenant_visible(customer_org_id))
    WITH CHECK (platform.tenant_visible(organization_id) OR platform.tenant_visible(customer_org_id));

COMMIT;
