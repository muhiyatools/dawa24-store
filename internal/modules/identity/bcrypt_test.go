package identity_test

import (
	"fmt"
	"strings"
	"testing"

	"golang.org/x/crypto/bcrypt"

	"github.com/muhiya/dawa24-store/internal/modules/identity"
)

// TestBcryptLaravelCompatibility proves that Go's bcrypt implementation verifies
// PHP/Laravel $2y$ password hashes natively.
func TestBcryptLaravelCompatibility(t *testing.T) {
	// Standard canonical Laravel default bcrypt hash
	const laravelDefaultSeedHash = "$2y$10$92IXUNpkjO0rOQ5byMi.Ye4oKoEa3Ro9llC/.og/at2.uheWG/igi"
	if !identity.CheckPassword(laravelDefaultSeedHash, "password") {
		t.Errorf("failed to verify canonical Laravel $2y$ seed hash for 'password'")
	}

	// Generate and verify 100 realistic $2y$ and $2a$ hashes
	for i := 0; i < 100; i++ {
		password := fmt.Sprintf("UserP@ssw0rd_%d_secure!", i)
		hashBytes, err := bcrypt.GenerateFromPassword([]byte(password), bcrypt.MinCost)
		if err != nil {
			t.Fatalf("failed to generate bcrypt hash: %v", err)
		}
		hash2a := string(hashBytes)

		// Transform to $2y$ format as generated by PHP's password_hash / Laravel
		hash2y := strings.Replace(hash2a, "$2a$", "$2y$", 1)

		// Verify $2a$
		if !identity.CheckPassword(hash2a, password) {
			t.Errorf("iteration %d: failed to verify $2a$ hash for %q", i, password)
		}

		// Verify $2y$
		if !identity.CheckPassword(hash2y, password) {
			t.Errorf("iteration %d: failed to verify $2y$ (Laravel) hash for %q", i, password)
		}

		// Verify wrong password fails
		if identity.CheckPassword(hash2y, password+"wrong") {
			t.Errorf("iteration %d: false positive on incorrect password", i)
		}
	}
}
