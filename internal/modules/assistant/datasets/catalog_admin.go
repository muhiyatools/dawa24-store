// The platform dashboard reads across organisations; that is what the admin
// screens do. What stays out is what no screen needs and a leak would hurt:
// password hashes, delivery PINs, payout destinations, sender accounts, stack
// traces and request payloads, audit before/after images, IP addresses, AI
// virtual keys. None of those columns is declared below, and the database role
// the executor runs as cannot SELECT them either (migration 214).

